#!/usr/bin/env python3
# Generates include/opope_tf16_pairs.h: the FP32 non-linear sequences (exp, GELU) of include/opope_tf16.h / opope_transformer.h
# for TWO independent rows, interleaved op by op (hides the result latency of the dependent chains: two rows at ~66 cycles per
# 8 ops instead of one row at ~72). The sequence of operations on each row is exactly the original one.
import sys

def exp_ops(neg):
    ops = [("vfmax.vf", "{x}", "{x}", -16.0)]
    if not neg:
        ops.append(("vfmin.vf", "{x}", "{x}", 20.0))
    ops += [("vfmul.vf", "{x}", "{x}", 0.015625), ("vfmv.v.f", "{t}", None, 0.0083333333),
            ("vfmul.vv", "{t}", "{t}", "{x}"), ("vfadd.vf", "{t}", "{t}", 0.0416666667),
            ("vfmul.vv", "{t}", "{t}", "{x}"), ("vfadd.vf", "{t}", "{t}", 0.1666666667),
            ("vfmul.vv", "{t}", "{t}", "{x}"), ("vfadd.vf", "{t}", "{t}", 0.5),
            ("vfmul.vv", "{t}", "{t}", "{x}"), ("vfadd.vf", "{t}", "{t}", 1.0),
            ("vfmul.vv", "{t}", "{t}", "{x}"), ("vfadd.vf", "{t}", "{t}", 1.0),
            ("vfmul.vv", "{x}", "{t}", "{t}")]
    ops += [("vfmul.vv", "{x}", "{x}", "{x}")] * 5
    return ops

def gelu_ops():
    # x = {x} (input and output), d = {d}, t = {t} (exp scratch, then the NR scratch), r = {r}
    ops = [("vfmul.vv", "{d}", "{x}", "{x}"), ("vfmul.vf", "{d}", "{d}", 0.044715), ("vfadd.vf", "{d}", "{d}", 1.0),
           ("vfmul.vv", "{d}", "{d}", "{x}"), ("vfmul.vf", "{d}", "{d}", -1.5957691216)]
    for o in exp_ops(False):
        ops.append(tuple(v.replace("{x}", "{d}") if isinstance(v, str) else v for v in o))
    ops.append(("vfadd.vf", "{d}", "{d}", 1.0))
    ops.append(("vrsub.vx", "{r}", "{d}", "MAGIC"))
    for _ in range(2):
        ops += [("vfmul.vv", "{t}", "{d}", "{r}"), ("vfrsub.vf", "{t}", "{t}", 2.0), ("vfmul.vv", "{r}", "{r}", "{t}")]
    ops.append(("vfmul.vv", "{x}", "{x}", "{r}"))
    return ops

def emit(op, regs):
    m, a, b, c = op
    a = a.format(**regs)
    if m == "vrsub.vx":
        return 'asm volatile("vrsub.vx %s, %s, %%0" ::"r"(0x7EF311C7u));' % (a, b.format(**regs))
    if m in ("vfmv.v.f",):
        return 'asm volatile("vfmv.v.f %s, %%0" ::"f"(%sf));' % (a, repr(c))
    if isinstance(c, float):
        return 'asm volatile("%s %s, %s, %%0" ::"f"(%sf));' % (m, a, b.format(**regs), repr(c))
    return 'asm volatile("%s %s, %s, %s");' % (m, a, b.format(**regs), c.format(**regs))

def macro(name, params, ops, regsets):
    lines = ["#define %s(%s)  \\" % (name, params) if params else "#define %s()  \\" % name, "  do { \\"]
    for i in range(len(ops)):
        for r in regsets:
            lines.append("    %s \\" % emit(ops[i], r))
    lines.append("  } while (0)")
    return "\n".join(lines)

out = ["// Copyright 2025 ETH Zurich and University of Bologna.",
       "// Licensed under the Apache License, Version 2.0, see LICENSE for details.",
       "// SPDX-License-Identifier: Apache-2.0", "",
       "// GENERATED by common/gen_pairs.py - do not edit. Two-row interleaved FP32 exp / GELU sequences (see the script).", "",
       "#ifndef OPOPE_TF16_PAIRS_H", "#define OPOPE_TF16_PAIRS_H", ""]
# exp for two rows: x/t register names are macro arguments (strings "v4" ...)
ops = exp_ops(True)
lines = ["// exp(x) for x <= 0 on two rows: (xa, ta) and (xb, tb) are LMUL=4 register groups (names as strings)",
         "#define TF16_EXP_NEG2(xa, ta, xb, tb)  \\", "  do { \\"]
for o in ops:
    for r in ({"x": '" xa "', "t": '" ta "'}, {"x": '" xb "', "t": '" tb "'}):
        lines.append("    %s \\" % emit(o, r))
lines.append("  } while (0)")
out.append("\n".join(lines))
out.append("")
# GELU on two rows: row A = v0 (x), v4 (d), v8 (t), v12 (r); row B = v16, v20, v24, v28; result in v0 and v16
out.append("// v0 <- gelu(v0), v16 <- gelu(v16) (tanh form), LMUL=4 groups; v4,v8,v12 and v20,v24,v28 are clobbered")
out.append(macro("TF16_GELU2", "", gelu_ops(), ({"x": "v0", "d": "v4", "t": "v8", "r": "v12"}, {"x": "v16", "d": "v20", "t": "v24", "r": "v28"})))
out.append("")
out.append("#endif")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
