"""Generate input and golden data for the transpose_blocks task as C headers.

Writes <out_root>/data/data.h (parameters, source, initial destination) and
<out_root>/golden/gold.h (expected destination after the transpose).

Byte values:
  1..127  block data
  -1      source padding (src_row_pitch_bytes - cols * block_bytes per row), never read
  -2      destination gaps (dst_row_pitch_bytes - rows * block_bytes per row), must stay -2

The golden array is the whole destination buffer, gaps included, so comparing the full buffer
also checks that gaps were not written.

Defaults are the globals below; every one can be overridden on the command line:
  python tools/gen_transpose_data.py [out_root] [--rows R] [--cols C] [--block-bytes B]
                                     [--src-row-pitch-bytes P] [--dst-row-pitch-bytes P]
                                     [--seed S]
"""
import argparse
from pathlib import Path

import numpy as np

# Default problem. Pitches are start-to-start distances in bytes and must be at least
# COLS * BLOCK_BYTES (source) and ROWS * BLOCK_BYTES (destination); the excess is padding/gap.
ROWS = 300
COLS = 200
BLOCK_BYTES = 3
SRC_ROW_PITCH_BYTES = 605  # 200 * 3 = 600 data bytes + 5 padding bytes
DST_ROW_PITCH_BYTES = 907  # 300 * 3 = 900 data bytes + 7 gap bytes
OUT_ROOT = "."  # gets data/data.h and golden/gold.h

SRC_PAD_VALUE = -1
DST_GAP_VALUE = -2
PER_LINE = 16


def make_source(rows, cols, bb, src_pitch, rng):
    src = np.full(rows * src_pitch, SRC_PAD_VALUE, dtype=np.int8)
    data = rng.integers(1, 128, (rows, cols * bb), dtype=np.int8)
    src.reshape(rows, src_pitch)[:, :cols * bb] = data
    return src


def transpose_golden(src, rows, cols, bb, src_pitch, dst_pitch):
    """dst[c*dst_pitch + r*bb + k] = src[r*src_pitch + c*bb + k], gaps left at -2."""
    dst = np.full(cols * dst_pitch, DST_GAP_VALUE, dtype=np.int8)
    blocks = src.reshape(rows, src_pitch)[:, :cols * bb].reshape(rows, cols, bb)
    dst.reshape(cols, dst_pitch)[:, :rows * bb] = blocks.transpose(1, 0, 2).reshape(cols, rows * bb)
    return dst


def c_array(qualifiers, name, size_macro, values):
    lines = []
    for i in range(0, len(values), PER_LINE):
        lines.append("    " + ", ".join(f"{v:4d}" for v in values[i:i + PER_LINE]) + ",")
    body = "\n".join(lines)
    return f"{qualifiers} int8_t {name}[{size_macro}] TRANSPOSE_DATA_ATTR = {{\n{body}\n}};\n"


def header(guard, comment, body):
    return (f"/* {comment} Generated by tools/gen_transpose_data.py; do not edit. */\n"
            f"#ifndef {guard}\n#define {guard}\n\n#include <stdint.h>\n\n"
            f"#ifndef TRANSPOSE_DATA_ATTR\n#define TRANSPOSE_DATA_ATTR\n#endif\n\n"
            f"{body}\n#endif /* {guard} */\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out_root", nargs="?", default=OUT_ROOT, help="directory that gets data/ and golden/")
    ap.add_argument("--rows", type=int, default=ROWS)
    ap.add_argument("--cols", type=int, default=COLS)
    ap.add_argument("--block-bytes", type=int, default=BLOCK_BYTES)
    ap.add_argument("--src-row-pitch-bytes", type=int, default=None,
                    help=f"default {SRC_ROW_PITCH_BYTES}, or cols*block_bytes if rows/cols/block-bytes changed")
    ap.add_argument("--dst-row-pitch-bytes", type=int, default=None,
                    help=f"default {DST_ROW_PITCH_BYTES}, or rows*block_bytes if rows/cols/block-bytes changed")
    ap.add_argument("--seed", type=int, default=0)
    a = ap.parse_args()
    if min(a.rows, a.cols, a.block_bytes) < 1:
        ap.error("rows, cols and block-bytes must be >= 1")

    # The default pitches only match the default shape; for another shape fall back to packed rows.
    shape_is_default = (a.rows, a.cols, a.block_bytes) == (ROWS, COLS, BLOCK_BYTES)
    if a.src_row_pitch_bytes is None:
        a.src_row_pitch_bytes = SRC_ROW_PITCH_BYTES if shape_is_default else a.cols * a.block_bytes
    if a.dst_row_pitch_bytes is None:
        a.dst_row_pitch_bytes = DST_ROW_PITCH_BYTES if shape_is_default else a.rows * a.block_bytes
    if a.src_row_pitch_bytes < a.cols * a.block_bytes:
        ap.error(f"src-row-pitch-bytes must be >= cols*block_bytes = {a.cols * a.block_bytes}")
    if a.dst_row_pitch_bytes < a.rows * a.block_bytes:
        ap.error(f"dst-row-pitch-bytes must be >= rows*block_bytes = {a.rows * a.block_bytes}")

    rows, cols, bb = a.rows, a.cols, a.block_bytes
    src_pitch = a.src_row_pitch_bytes
    dst_pitch = a.dst_row_pitch_bytes
    src = make_source(rows, cols, bb, src_pitch, np.random.default_rng(a.seed))
    gold = transpose_golden(src, rows, cols, bb, src_pitch, dst_pitch)
    dst_init = np.full(cols * dst_pitch, DST_GAP_VALUE, dtype=np.int8)

    params = (f"#define ROWS        {rows}u\n"
              f"#define COLS        {cols}u\n"
              f"#define BLOCK_BYTES {bb}u\n"
              f"#define SRC_PITCH   {src_pitch}u  /* cols*block_bytes + {src_pitch - cols * bb} */\n"
              f"#define DST_PITCH   {dst_pitch}u  /* rows*block_bytes + {dst_pitch - rows * bb} */\n"
              f"#define SRC_SIZE    {src.size}u  /* rows * src_pitch */\n"
              f"#define DST_SIZE    {gold.size}u  /* cols * dst_pitch */\n"
              f"#define SEED        {a.seed}\n\n")

    root = Path(a.out_root)
    (root / "data").mkdir(parents=True, exist_ok=True)
    (root / "Golden").mkdir(parents=True, exist_ok=True)
    data_body = (params
                 + "/* Source: block data 1..127, row padding -1. Read-only. */\n"
                 + c_array("const", "src_dram", "SRC_SIZE", src)
                 + "\n/* Destination before the call: all -2. */\n"
                 + c_array("", "dst_dram", "DST_SIZE", dst_init))
    (root / "data" / "data.h").write_text(
        header("TRANSPOSE_DATA_H", "transpose_blocks inputs.", data_body))
    gold_body = (f"#define GOLD_SIZE {gold.size}u  /* = DST_SIZE */\n\n"
                 "/* Expected destination after transpose_blocks: data 1..127, gaps -2. */\n"
                 + c_array("const", "golden", "GOLD_SIZE", gold))
    (root / "Golden" / "gold.h").write_text(
        header("TRANSPOSE_GOLD_H", "transpose_blocks golden output.", gold_body))

    print(f"rows={rows} cols={cols} block_bytes={bb} src_pitch={src_pitch} dst_pitch={dst_pitch}")
    print(f"src {src.size} B + dst {gold.size} B = {src.size + gold.size} B "
          f"({'exceeds' if src.size + gold.size > 128 * 1024 else 'fits in'} 128 KiB L1)")
    print(f"wrote {root / 'data' / 'data.h'} and {root / 'Golden' / 'gold.h'}")


if __name__ == "__main__":
    main()
