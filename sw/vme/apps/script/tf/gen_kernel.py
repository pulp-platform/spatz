"""Emit kernel/matmul_relu.c: fused Z^T = relu(W^T X) on Spatz VFU + OPE (O-POPE P5 shape)."""
import argparse
import pathlib

ap = argparse.ArgumentParser()
ap.add_argument("--loadpos", type=int, default=4, help="issue next-group loads after this many vtfmm (0..8)")
ap.add_argument("--drainpos", default="1,5", help="vtfmm indices after which the two drain rows are issued")
ap.add_argument("--relupos", type=int, default=-1, help="vtfmm index for the ReLU stage (-1: with the loads)")
ap.add_argument("--taillag", type=int, default=0, help="tail: ReLU row r after drain row r+lag")
ap.add_argument("--bias", type=int, default=0,
                help="1: Z^T = relu(W^T X + bias) (O-POPE P5); the bias is one extra K-pair per block")
ap.add_argument("--relubuf", type=int, default=0, help="ReLU row buffers (1 or 2; default 1 with bias, else 2)")
ap.add_argument("--tail", default="m8", help="vt: final tile rows via vtmv.v.t + vfmax + vse; m8: vtse + m8 ReLU")
ap.add_argument("--post", default="relu", help="relu: fused ReLU; none: plain GeMM (+bias), Z^T stored")
ap.add_argument("--name", default="mr_kernel")
ap.add_argument("--out", default=None)
ARGS = ap.parse_args()
if ARGS.relubuf == 0:
    ARGS.relubuf = 1 if ARGS.bias else 2
assert not (ARGS.bias and ARGS.relubuf == 2), "the bias K-pair needs v28-v30 (single ReLU buffer)"

HDR = """// Copyright 2026 ETH Zurich and University of Bologna.
// SPDX-License-Identifier: Apache-2.0
// GENERATED by script/gen_kernel.py -- edit the generator, not this file.
//
// Fused Z^T = relu(W^T X) on Spatz VFU + OPE (TE=16, CE=8, VLEN=512), O-POPE P5 shape:
// COUT=192 (tile rows), T=64 (tile columns), C=128 (64 packed FP16 K-pairs), FP32 output Z^T[192][64].
//
// Staggered (ping-pong) schedule: 24 blocks of 32 channels x 16 tokens (cout-block cb = 0..5 outer,
// token tile tt = 0..3 inner). Block j accumulates on one tile pair (P0 = mt0/mt4 for even j, P1 = mt8/mt12
// for odd j) while the other pair, holding block j-1, is drained with vtse32 (one row of each tile per
// K-group). A block is 16 K-groups; a K-group is 4 K-pairs = 8 vtfmm (32 OPE cycles) and also carries
//   * the e32,m4 post-increment loads of the NEXT K-group operands into the other register set
//     (S0 = v0/v4/v8, S1 = v16/v20/v24), issued after the first vtfmm of the group so that the previous
//     group's vtfmm have already read those registers (no WAR stall in the issue stream);
//   * two drain rows (vtse32) of the idle tile pair;
//   * one stage of a software-pipelined ReLU (rows of 64 contiguous floats, e32,m4) over the previous
//     cout-block: even groups load row n (v28); odd groups store row n-1 (v12), then vfmax row n into v12.
//     A store is issued two K-groups after the vfmax it depends on, so it never blocks the issue stream.
// The ReLU of cout-block cb-1 runs during cout-block cb; cout-block 0 uses a ReLU-free block variant.
// VFU arithmetic and OPE MACs share the three VRF operand read ports (round-robin), so the ReLU's vfmax
// cycles add to the OPE cycles: lower bound = 12288 (OPE) + 12288/8 (vfmax) = 13824 cycles.
// The tail interleaves the drain of the last block with the ReLU of the cout-block 5 rows it completes.
"""

GPR = {"zero": 0, "ra": 1, "sp": 2, "gp": 3, "tp": 4, "t0": 5, "t1": 6, "t2": 7, "s0": 8, "s1": 9,
       **{f"a{i}": 10 + i for i in range(8)}, **{f"s{i}": 16 + i for i in range(2, 12)},
       "t3": 28, "t4": 29, "t5": 30, "t6": 31}


def vle32_rrpost(vd, rs1, rs2):
    """p.vle32.v.rrpost vd, (rs1), rs2: unit-stride e32 load, then rs1 += rs2 (Snitch custom-3).
    The toolchain has no mnemonic for it, so the encoding is emitted (hw/ip/snitch/src/riscv_instr.sv)."""
    w = (0b110000 << 26) | (1 << 25) | (GPR[rs2] << 20) | (GPR[rs1] << 15) | (0b110 << 12) | (vd << 7) | 0x7B
    return f".word 0x{w:08x} /* p.vle32.v.rrpost v{vd}, ({rs1}), {rs2} */"


L = []


def e(*xs):
    L.extend(xs)


S0, S1 = (0, 4, 8), (16, 20, 24)
MMODE = ["msetmtype t4, t5", "msettn zero, t6"]
VMODE = "vsetvli zero, s0, e32, m4, ta, ma"


def group(cx, cy, cur, nxt, odd, relu, extra_after_loads=()):
    """One K-group. Registers: a0/a1/a2 operand streams (t1 = 512 B A-stride, t2 = 256 B B-stride),
    a3/a4 drain addresses, a5/a6 drain TSS, a7 ReLU load address, t0 ReLU store address."""
    a0, a1, b = cur
    n0, n1, nb = nxt
    loads = [VMODE, vle32_rrpost(n0, "a0", "t1"), vle32_rrpost(n1, "a1", "t1"), vle32_rrpost(nb, "a2", "t2")]
    rstage = []
    if relu and relu[0] == "ls":     # single buffer: store row n-1, load row n
        rstage = [f"vse32.v v{relu[1]}, (t0)", f"vle32.v v{relu[1]}, (a7)", "mv t0, a7", "add a7, a7, t2"]
    elif relu and relu[0] == "m":    # single buffer: vfmax row n in place
        rstage = [f"vfmax.vf v{relu[1]}, v{relu[1]}, ft0"]
    elif relu and relu[0] == "ld":
        rstage = [f"vle32.v v{relu[1]}, (a7)"]
    elif relu and relu[0] == "mx":
        x, xp = relu[1], relu[2]
        rstage = [f"vse32.v v{xp}, (t0)", f"vfmax.vf v{x}, v{x}, ft0", "mv t0, a7", "add a7, a7, t2"]
    if ARGS.relupos < 0:
        loads += rstage
        rstage = []
    loads += list(extra_after_loads) + MMODE
    macs = []
    for k in range(4):
        macs += [f"vtfmm.tvv {cx}, v{a0+k}, v{b+k}", f"vtfmm.tvv {cy}, v{a1+k}, v{b+k}"]
    dpos = [int(x) for x in ARGS.drainpos.split(",")]
    drains = [["vtse32 a5, (a3)", "addi a5, a5, 1", "add a3, a3, t2"],
              ["vtse32 a6, (a4)", "addi a6, a6, 1", "add a4, a4, t2"]]
    for i, m in enumerate(macs):
        if i == ARGS.loadpos:
            e(*loads)
        if rstage and i == ARGS.relupos:
            e(VMODE, *rstage, *MMODE)
        e(m)
        for d, pos in zip(drains, dpos):
            if i + 1 == pos:
                e(*d)
    if ARGS.loadpos >= 8:
        e(*loads)


RA, RB = 12, 28   # ReLU row buffers (e32,m4), alternating per row (RB unused with a single buffer)
# bias K-pair registers (single ReLU buffer only): v28 = bias {hi,lo} of the upper tile rows, v29 = lower tile,
# v30 = {1.0, 1.0}; loaded with one e32,m4 load per block from the per-cout-block bias vector (64 words)


def stages(relu):
    """ReLU stage of the 4 K-groups of one loop body: rows n (RA) and n+1 (RB)."""
    if not relu:
        return [None] * 4
    if ARGS.relubuf == 1:
        return [("ls", RA), ("m", RA), ("ls", RA), ("m", RA)]
    return [("ld", RA), ("mx", RA, RB), ("ld", RB), ("mx", RB, RA)]


def block(cx, cy, tsx, tsy, tag, relu):
    """16 K-groups on (cx, cy) = 3 x 4-group loop body + 4 peeled groups. On exit: operand pointers at
    group 0 of the next block (prefetched into S0), drain registers aimed at this block, tt advanced."""
    st = stages(relu)
    sets = [(S0, S1), (S1, S0), (S0, S1), (S1, S0)]
    e(f"vtzero {cx}", f"vtzero {cy}")
    if ARGS.bias:   # bias = one extra K-pair: {hi, lo} x {1.0, 1.0} (operands loaded by the previous block)
        e(f"vtfmm.tvv {cx}, v28, v30", f"vtfmm.tvv {cy}, v29, v30")
    e("li s7, 3", f".Lk_{tag}:")
    for g in range(4):
        group(cx, cy, *sets[g], g % 2 == 1, st[g])
    e("addi s7, s7, -1", f"bnez s7, .Lk_{tag}")
    for g in range(3):
        group(cx, cy, *sets[g], g % 2 == 1, st[g])
    # before group 15: select the operand rewind for its prefetch (next block, group 0)
    e("bne s5, s8, .Lsc_" + tag,          # s8 == 3
      "sub a2, a2, s10",                  # next cout-block: B back to token tile 0 (16 KiB)
      *(["addi s3, s3, 256"] if ARGS.bias else []),   # next cout-block's bias vector
      "li t3, 8000",                      # base(cb+1, 0) - base(cb, 3)
      "j .Lop_" + tag,
      ".Lsc_" + tag + ":",
      "sub a0, a0, s9", "sub a1, a1, s9",  # same cout-block: A back by one block (8 KiB)
      "li t3, 64",                        # base(cb, tt+1) - base(cb, tt)
      ".Lop_" + tag + ":")
    group(cx, cy, *sets[3], True, st[3], ["vle32.v v28, (s3)"] if ARGS.bias else [])
    # the next block drains this one: s11 = base(cb, tt) = z + cb*8192 + tt*64
    e("mv a3, s11", "add a4, s11, s4", "add s11, s11, t3",
      f"li a5, {tsx}", f"li a6, {tsy}",
      "addi s5, s5, 1", "andi s5, s5, 3")


SAVED = [f"s{i}" for i in range(12)]
# Scalar stores wait for outstanding vector loads, so save the callee-saved registers first, then issue
# the first K-group loads, then the setup the first K-group needs; the rest follows the loads.
e("addi sp, sp, -64", *[f"sw {r}, {4*i}(sp)" for i, r in enumerate(SAVED)],
  "li t1, 512", "li t2, 256", "li s0, 64", "mv t3, a1", "addi a1, a0, 256",
  VMODE, vle32_rrpost(0, "a0", "t1"), vle32_rrpost(4, "a1", "t1"), vle32_rrpost(8, "t3", "t2"),
  "mv s2, a2", "mv a2, t3",
  "li t4, 16450", "li t5, 0xC8", "li t6, 16",
  "msetmtype t4, t5", "msettn zero, t6", "msettm zero, t6",
  "vtzero mt8", "vtzero mt12",
  "li a5, 0x40000000", "li a6, 0x60000000",
  "li s8, 3", "li s9, 8192", "li s10, 16384", "fmv.w.x ft0, zero", "li s5, 0")
e("mv s11, s2", "li s4, 4096")   # s11 = drain base of block 0 = (0, 0)
if ARGS.bias:
    e("mv s3, a3", VMODE, "vle32.v v28, (s3)", *MMODE)   # bias operands of block 0
# block 0 drains a dummy (zeroed) pair into rows of the cb = 5 region, rewritten later
e("li t3, 40960", "add a3, s2, t3", "addi a3, a3, 192", "add a4, a3, s4")
# cout-block 0: no ReLU (nothing finished yet)
e("li s1, 2", ".Lc0:")
block("mt0", "mt4", "0x00000000", "0x20000000", "c0p0", False)
block("mt8", "mt12", "0x40000000", "0x60000000", "c0p1", False)
e("addi s1, s1, -1", "bnez s1, .Lc0")
# ReLU stream starts at cout-block 0; prime the pipeline store target with a harmless row (cb = 5 region)
e("mv a7, s2", "li t3, 45056", "add t0, s2, t3")
e("li s1, 10", ".Lst:")
block("mt0", "mt4", "0x00000000", "0x20000000", "p0", ARGS.post == "relu")
block("mt8", "mt12", "0x40000000", "0x60000000", "p1", ARGS.post == "relu")
e("addi s1, s1, -1", "bnez s1, .Lst")
# ---- tail ----
if ARGS.post == "smax":
    # drain block 23 (cb = 5, tt = 3) while the VFU starts the softmax column max over the 160 rows that are
    # already final (cout-blocks 0..4): accumulators v0 / v4 (even / odd rows), loads 4 rows ahead in a ring of
    # 6 e32,m4 buffers. The softmax kernel continues from row 160 with v0 / v4 live.
    RING = [8, 12, 16, 20, 24, 28]
    e("li t3, 0xf149f2ca", "fmv.w.x ft8, t3", VMODE, "vfmv.v.f v0, ft8", "vfmv.v.f v4, ft8", "mv a7, s2")
    for r in range(4):
        e(vle32_rrpost(RING[r], "a7", "t2"))
    NR = 156                                     # rows reduced here (multiple of 6, even); the rest in softmax
    row = 0
    for it in range(16):
        e(*MMODE, "vtse32 a5, (a3)", "addi a5, a5, 1", "add a3, a3, t2",
          "vtse32 a6, (a4)", "addi a6, a6, 1", "add a4, a4, t2", VMODE)
        while row < NR * (it + 1) // 16:
            e(f"vfmax.vv v{4 * (row % 2)}, v{4 * (row % 2)}, v{RING[row % 6]}")
            if row + 4 < NR:
                e(vle32_rrpost(RING[(row + 4) % 6], "a7", "t2"))
            row += 1
    e("addi s11, a4, -4")
elif ARGS.post == "none":
    # drain block 23 (cb = 5, tt = 3)
    e("li s7, 16", ".Ltdn:", "vtse32 a5, (a3)", "addi a5, a5, 1", "add a3, a3, t2",
      "vtse32 a6, (a4)", "addi a6, a6, 1", "add a4, a4, t2", "addi s7, s7, -1", "bnez s7, .Ltdn",
      "addi s11, a4, -4")
else:
    # ReLU pipeline: v12 holds row 31 of cb = 4? (no: odd group stored row n-1 and vfmax'ed row n into v12)
    e(VMODE, f"vse32.v v{RA if ARGS.relubuf == 1 else RB}, (t0)", *MMODE)   # last ReLU row of cb = 4
    if ARGS.tail == "vt2":
        # Tail. cb = 5 output rows 0..31 are contiguous; tokens 0..47 are final in z (block 22 was drained during
        # block 23), tokens 48..63 are in mt8 (rows 0..15) / mt12 (rows 16..31). Iteration k handles output rows
        # 2k, 2k+1: one e32,m8 load brings both rows (stale tokens 48..63 in registers base+3 / base+7), vtmv.v.t
        # reads the two tile rows into separate registers, a VFU vmv.v.v merges them (the VFU scoreboard orders it
        # after the load; a tile move into the load's registers would not be ordered), then one m8 vfmax and one
        # m8 store. No vtse32 and no reload of drained data. Pair buffers v0/v8, tile-row buffers v16-17/v18-19.
        PS, TS = [0, 8], [16, 18]
        MC32 = ["msetmtypei 1, 2, 0", "msettn zero, t6", "msettm zero, t6"]
        e("li t3, 40960", "add s7, s2, t3", "mv a7, s7", "li s9, 512", "li s10, 128")
        for k in range(17):
            c, p_ = k % 2, (k - 1) % 2
            if k >= 1:
                e("vsetvli zero, s10, e32, m8, ta, ma", f"vfmax.vf v{PS[p_]}, v{PS[p_]}, ft0",
                  f"vse32.v v{PS[p_]}, (a7)", "add a7, a7, s9")
            if k < 16:
                ts = "a5" if k < 8 else "a6"
                pb, tb = PS[c], TS[c]
                e("vsetvli zero, s10, e32, m8, ta, ma", vle32_rrpost(pb, "s7", "s9"), *MC32,
                  f"vtmv.v.t v{tb}, {ts}", f"addi {ts}, {ts}, 1", f"vtmv.v.t v{tb+1}, {ts}", f"addi {ts}, {ts}, 1",
                  f"vmv.v.v v{pb+3}, v{tb}", f"vmv.v.v v{pb+7}, v{tb+1}")
        e("mv s11, a7")
    elif ARGS.tail == "vt":
        # Tail. Output rows of cb = 5: tokens 0..47 are final in z since block 23 drained block 22; tokens
        # 48..63 are in mt8 (rows 0..15) / mt12 (rows 16..31). Batch i handles output rows i and 16+i:
        #  A: ReLU of tokens 0..47 in memory (e32,m4, vl=48 post-increment loads), two buffer sets;
        #  B: tile rows -> VRF (vtmv.v.t, OPE VRF-side port, parallel to the VLSU) -> vfmax -> vse to tokens 48..63.
        # A and B write disjoint bytes, so they need no mutual ordering. No vtse32 and no reload of drained data.
        # B (tile rows): 16 vtmv.v.t into v16..v31 under one SEW32 matrix config, two e32,m8 vfmax (8 rows each),
        # 16 row stores; once for mt8 (rows 0..15) and once for mt12 (rows 16..31).
        # A (memory, tokens 0..47): 8 segments of 4 rows (v0, v4, v8, v12): load, vfmax, store.
        # The A phases are interleaved with the B chunks so that neither waits on its own dependencies.
        MC32 = ["msetmtypei 1, 2, 0", "msettn zero, t6", "msettm zero, t6"]
        def b_vt(ts):
            return MC32 + sum(([f"vtmv.v.t v{16+r}, {ts}", f"addi {ts}, {ts}, 1"] for r in range(16)), [])
        B_MAX = ["vsetvli zero, s10, e32, m8, ta, ma", "vfmax.vf v16, v16, ft0", "vfmax.vf v24, v24, ft0"]
        def b_st(r0, r1, ptr):
            return MC32 + sum(([f"vse32.v v{16+r}, ({ptr})", f"add {ptr}, {ptr}, t2"] for r in range(r0, r1)), [])
        def a_ld():
            return ["vsetvli zero, s9, e32, m4, ta, ma"] + [vle32_rrpost(v, "s7", "t2") for v in (0, 4, 8, 12)]
        A_MX = ["vsetvli zero, s9, e32, m4, ta, ma"] + [f"vfmax.vf v{v}, v{v}, ft0" for v in (0, 4, 8, 12)]
        A_ST = ["vsetvli zero, s9, e32, m4, ta, ma"] + sum(([f"vse32.v v{v}, (a7)", "add a7, a7, t2"] for v in (0, 4, 8, 12)), [])
        e("li t3, 40960", "add s7, s2, t3", "mv a7, s7", "li s9, 48", "li s10, 128")
        seq = []
        for half, (ts, ptr) in enumerate((("a5", "a3"), ("a6", "a4"))):
            seq += [a_ld(), b_vt(ts), A_MX, A_ST,
                    a_ld(), B_MAX, A_MX, b_st(0, 8, ptr), A_ST,
                    a_ld(), b_st(8, 16, ptr), A_MX, A_ST,
                    a_ld(), A_MX, A_ST]
        for c in seq:
            e(*c)
        e("mv s11, a7")
    else:
        # Drain block 23 (cb = 5, tt = 3): iteration j stores tile rows 2j, 2j+1 of both tiles, which completes
        # output rows 2j, 2j+1 (upper) and 16+2j, 17+2j (lower) of cb = 5; two consecutive output rows are
        # contiguous, so their ReLU is one e32,m8 load / vfmax / store. Pipeline: load pair j-lag, then
        # vfmax + store pair j-lag-1, two m8 buffers per stream (the whole VRF is free now).
        lag = ARGS.taillag
        BX, BY = [0, 8], [16, 24]
        e("li t3, 40960", "add a7, s2, t3",        # a7: next upper row pair to load (rows 0,1 of cb = 5)
          "li t3, 4096", "add t0, a7, t3",          # t0: next lower row pair to load (rows 16,17)
          "mv s7, a7", "mv s11, t0", "li s4, 512", "li t3, 128")
        for j in range(8 + lag + 1):
            if j < 8:
                e(*MMODE, *(["vtse32 a5, (a3)", "addi a5, a5, 1", "add a3, a3, t2",
                             "vtse32 a6, (a4)", "addi a6, a6, 1", "add a4, a4, t2"] * 2))
            ops = []
            r = j - lag
            if 0 <= r < 8:
                ops += [f"vle32.v v{BX[r % 2]}, (a7)", f"vle32.v v{BY[r % 2]}, (t0)", "add a7, a7, s4", "add t0, t0, s4"]
            if 0 <= r - 1 < 8:
                q = r - 1
                ops += [f"vfmax.vf v{BX[q % 2]}, v{BX[q % 2]}, ft0", f"vfmax.vf v{BY[q % 2]}, v{BY[q % 2]}, ft0",
                        f"vse32.v v{BX[q % 2]}, (s7)", f"vse32.v v{BY[q % 2]}, (s11)", "add s7, s7, s4", "add s11, s11, s4"]
            if ops:
                e("vsetvli zero, t3, e32, m8, ta, ma", *ops)
e("fence rw, rw", "lw t3, -4(s11)")
e(*[f"lw {r}, {4*i}(sp)" for i, r in enumerate(SAVED)], "addi sp, sp, 64", "ret")

body = "\n".join(f'    "{x}\\n"' for x in L)
N = ARGS.name
out = (HDR + f"\n#include <stdint.h>\n\nvoid {N}(const uint32_t *astream, const uint32_t *bpan, float *z, const uint32_t *bpair);\n\n"
       f'__asm__(\n    ".text\\n"\n    ".balign 64\\n"\n    ".globl {N}\\n"\n'
       f'    ".type {N}, @function\\n"\n    "{N}:\\n"\n' + body +
       f'\n    ".size {N}, .-{N}\\n");\n')
dst = pathlib.Path(ARGS.out) if ARGS.out else pathlib.Path("kernel") / ("gemm_relu.c" if ARGS.bias else "matmul_relu.c")
dst.write_text(out)
n_instr = sum(1 for x in L if not x.endswith(":"))
print(f"wrote {dst} ({n_instr} instructions, ~{4*n_instr} B of code)")
