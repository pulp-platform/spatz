"""P2 (GeMM -> GELU), O-POPE shape C=128, T=64, COUT=192: FUSED VME kernel + data.

Inputs drawn exactly as baseline tf16_data.p_lin(mode="p2") (default_rng(21)); only the layouts differ:
  A stream [6][33][2 tiles][2 K-pairs][16] (W padded with K-pair 64 = {bias hi, bias lo}),
  B = x packed token-half-major [2][65][32] (K-pair 64 = {1, 1}), z [192][64] FP32 (output, GELU in place).
OPE: 2x2 blocks (32 rows x 32 tokens), row-block-major; the first row block runs alone (OPE only, batched), then
the GELU (TF16_GELU2, rows 2s / 2s+1 per step, one exact rewrite, see fusegen.py) runs over z with the remaining
K-groups in its T3 register window and the drains in 2-row chunks in the other slots.
"""
import argparse, pathlib, sys
import numpy as np
sys.path.insert(0, str(pathlib.Path(__file__).parent))
import fusegen as fg

F32 = np.float32
ap = argparse.ArgumentParser()
ap.add_argument("--data", required=True)
ap.add_argument("--kernel", required=True)
ap.add_argument("--header", default=str(pathlib.Path(__file__).resolve().parents[2] / "include" / "opope_tf16_pairs.h"))
ap.add_argument("--margin", type=int, default=2)
ap.add_argument("--mode", default="p2", choices=["p2", "p3"])
ap.add_argument("--wstep", type=int, default=2)
ap.add_argument("--xstep", type=int, default=2)
ap.add_argument("--loop", type=int, default=1, help="1: GELU-only steps (OPE done) as a loop of 2 steps (I-cache)")
ap.add_argument("--rowprov", type=int, default=0)
ap.add_argument("--hb", type=int, default=0, help="leading row blocks computed as ping-pong half blocks")
ap.add_argument("--halfrows", type=int, default=0, help="1: GELU of row block 0 on 2-row x 32-token vectors per token half")
A = ap.parse_args()
P3 = A.mode == "p3"
C, T, O = (96, 64, 176) if P3 else (128, 64, 192)
OP = -(-O // 32) * 32                                # A rows padded to whole 32-row blocks
KP = C // 2 + 1
KG = -(-KP // 2)

def rnd(rng, shape, scale=1.0): return (rng.standard_normal(shape) * scale).astype(F32)
def wgt(rng, cin, cout): return (rng.standard_normal((cin, cout)) / np.sqrt(cin)).astype(F32)
def gelu(x): return 0.5 * x * (1.0 + np.tanh(np.sqrt(2.0 / np.pi) * (x + 0.044715 * x ** 3)))
def h16(x): return np.asarray(x).astype(np.float16).astype(np.float64)
def ln_na(x):
    x = x.astype(np.float64); m = x.mean(axis=0, keepdims=True); v = ((x - m) ** 2).mean(axis=0, keepdims=True)
    return (x - m) / np.sqrt(v + 1e-5)
def fold_ln(w, g, b, bias):
    w64 = w.astype(np.float64)
    return (w64 * g.astype(np.float64)[:, None]).astype(np.float16), (bias.astype(np.float64) + w64.T @ b.astype(np.float64)).astype(F32)
rng = np.random.default_rng(21)
w = wgt(rng, C, O).astype(np.float16)
bias = 0.1 * rnd(rng, O)
if P3:
    x = rnd(rng, (C, T)); gg = 1 + 0.1 * rnd(rng, C); bb = 0.1 * rnd(rng, C)
    w, bias = fold_ln(w, gg, bb, bias)
    act = h16(ln_na(x))
else:
    x16 = rnd(rng, (C, T)).astype(np.float16)
    act = x16.astype(np.float64)
z = gelu(w.astype(np.float64).T @ act + bias.astype(np.float64)[:, None])
hi = bias.astype(np.float16); lo = (bias.astype(np.float64) - hi.astype(np.float64)).astype(np.float16)
wext = np.zeros((C + 2, OP), np.float16); wext[:C, :O] = w; wext[C, :O] = hi; wext[C + 1, :O] = lo
if P3:
    arrays = {"d_a": fg.pack22(fg.packwords(wext)), "d_x": x.view(np.uint32), "d_lnone": np.full(32, 0x3C003C00, np.uint32),
              "d_golden": z.astype(F32).view(np.uint32)}
else:
    xw = fg.packwords(x16)                                             # [64][64]
    xpk = np.zeros((2, KP, 32), np.uint32)
    for hh in (0, 1):
        xpk[hh, :C // 2] = xw[:, 32 * hh:32 * hh + 32]
        xpk[hh, C // 2] = 0x3C003C00
    arrays = {"d_a": fg.pack22(fg.packwords(wext)), "d_xpk": xpk.ravel(), "d_golden": z.astype(F32).view(np.uint32)}
out = [f"// GENERATED by gemm_gelu.py --mode {A.mode}", f"#define KP_SIZE {KP}", "#pragma once", "#include <stdint.h>", f"#define C_SIZE {C}", f"#define T_SIZE {T}",
       f"#define COUT_SIZE {O}"]
for k, v in arrays.items():
    v = np.asarray(v).ravel()
    out.append(f"static uint32_t {k}[{len(v)}] __attribute__((section(\".data\"), aligned(64))) = {{" +
               ",".join(f"0x{int(q):08x}" for q in v) + "};")
pathlib.Path(A.data).write_text("\n".join(out) + "\n")

# ------------------------------------------------------------------ kernel ----------------------------------------
# s6 A, s4 xpk, s2 z, t1 = 256, s0 = 64, t4/t5/t6 matrix config, s9 = 0x7EF311C7; GELU: a5 load ptr, a6 store ptr
L = []
e = L.extend
def E(*x): L.extend(x)
q = fg.Queue()
pend = []
for rb in range(OP // 32):
    if rb < A.hb:
        hbs = [(0, 0), (0, 1), (1, 0), (1, 1)]           # (half, cb), alternating tile pairs
        for j, (hf, cb) in enumerate(hbs):
            pend = fg.halfblock22(q, pair=j % 2, half=hf, abase="s6", aoff=rb * KG * 256, bbase="s4", boff=cb * KP * 128,
                                  kp=KP, zreg="s2", zoff=rb * 32 * 256 + cb * 128, zstride="t1", zrow_bytes=256,
                                  req_fn=lambda gi: None, prov=("zh", rb, hf, cb), interleave=pend)
        continue
    q.q += pend; pend = []
    for cb in (0, 1):
        fg.block22(q, abase="s6", aoff=rb * KG * 256, bbase="s4", boff=cb * KP * 128, kp=KP, zreg="s2",
                   zoff=rb * 32 * 256 + cb * 128, zstride="t1", zrow_bytes=256, req_fn=lambda gi: None,
                   ntiles=4 if (rb + 1) * 32 <= O else 2,
                   prov=[("zh", rb, 0, cb), ("zh", rb, 1, cb)],
                   rowprov=(lambda r, cb=cb: ("zr", cb, r)) if (rb == 0 and A.halfrows and A.rowprov) else None)
q.q += pend
g = fg.Gelu(A.header, {0x7EF311C7: "s9"})
NS = O * T // 128
def need(s):
    r = min(2 * s + 1, O - 1)
    return [("zh", r // 32, (r % 32) // 16, 0), ("zh", r // 32, (r % 32) // 16, 1)]
WINLAST = g.t3_first + 1 - 12
WIN = set(range(2, WINLAST + 1, A.wstep))
FLUSH = max(WIN) + 2
XWIN = set(range(FLUSH + 2, g.N, A.xstep))
REGS = (12, 28)

E(*fg.prologue(), "mv s6, a0", "mv s4, a1", "mv s2, a2", "li t1, 256", "li s0, 64", "li t4, 16450", "li t5, 0xC8",
  "li t6, 16", *g.const_init(), *fg.MM, "msettm zero, t6")
def done(tags): return all(t in q.done for t in tags)
STEPS = ([("half", h, j) for h in (0, 1) for j in range(8)] + [("full", s) for s in range(16, NS)]) if A.halfrows else \
        [("full", s) for s in range(NS)]
assert len(STEPS) == NS
V32 = "vsetvli zero, s1, e32, m2, ta, ma"           # s1 = 32
def rows_of(st):
    return list(range(4 * st[2], 4 * st[2] + 4)) if st[0] == "half" else [2 * st[1], 2 * st[1] + 1]
def need_st(st):
    if st[0] == "half":
        return [("zr", st[1], 4 * st[2] + 3)] if A.rowprov else [("zh", 0, 0, st[1]), ("zh", 0, 1, st[1])]
    r = 2 * st[1] + 1
    return [("zh", r // 32, (r % 32) // 16, 0), ("zh", r // 32, (r % 32) // 16, 1)]
def loads(st, m):
    """load step st into the x registers of map m (pointer a5 already at its first row)"""
    if st[0] == "half":
        x, y = m["v0"], m["v16"]
        return [V32, fg.rr(x, "a5", "t1"), fg.rr(x + 2, "a5", "t1"), fg.rr(y, "a5", "t1"), fg.rr(y + 2, "a5", "t1"), fg.VM64]
    return [fg.rr(m["v0"], "a5", "t1"), fg.rr(m["v16"], "a5", "t1")]
def ptr_fix(cur, nxt):
    """a5 adjustment between the loads of step cur and nxt (a5 points after the last row loaded)"""
    if nxt[0] == "half" and cur[0] == "half" and nxt[1] != cur[1]:
        return [f"addi a5, s2, {128 * nxt[1]}"]
    if nxt[0] == "full" and cur[0] == "half":
        return [f"li t3, {2 * nxt[1] * 256}", "add a5, s2, t3"]
    return []
def stores(st, m):
    if st[0] == "half":
        x, y = m["v0"], m["v16"]
        base = [f"li t3, {4 * st[2] * 256 + 128 * st[1]}", "add a6, s2, t3"]
        return base + [V32, f"vse32.v v{x}, (a6)", "add a6, a6, t1", f"vse32.v v{x + 2}, (a6)", "add a6, a6, t1",
                       f"vse32.v v{y}, (a6)", "add a6, a6, t1", f"vse32.v v{y + 2}, (a6)", fg.VM64]
    return [f"li t3, {2 * st[1] * 256}", "add a6, s2, t3", f"vse32.v v{m['v0']}, (a6)", "add a6, a6, t1",
            f"vse32.v v{m['v16']}, (a6)"]
def emit_step(k):
    st = STEPS[k]; nxt = STEPS[k + 1] if k + 1 < NS else None
    nm = g.pmap(k + 1)
    def hook(i):
        if i in WIN:
            q.slot(E, REGS)
        elif i in XWIN:
            q.xfer_slot(E)
        if i == FLUSH:
            q.flush(E, REGS)
        if i == g.loadat and nxt is not None:
            E(*ptr_fix(st, nxt), *loads(nxt, nm))
    g.step(E, k, hook)
    E(*stores(st, g.pmap(k)))
hb_groups = [i for i, op in enumerate(q.q) if op.kind == "group"][:A.hb * 4 * KG]
LASTG = hb_groups[-1] if hb_groups else -1
q.batched(E, until=lambda: q.i > LASTG and done(need_st(STEPS[min(1 + A.margin, NS - 1)])) if not A.halfrows else
          done(need_st(STEPS[0])) and done(need_st(STEPS[min(1 + A.margin, 7)])))
E(fg.VM64, "mv a5, s2", *loads(STEPS[0], g.pmap(0)))
k = 0
while k < NS:
    st = STEPS[k]
    if A.loop and q.empty() and q.pending is None and k % 2 == 0 and NS - k >= 4 and st[0] == "full" and k >= 18:
        n = (NS - k - 2) // 2
        E(f"li a7, {n}", f"li t3, {2 * STEPS[k][1] * 256}", "add a6, s2, t3", ".balign 32", ".Lgl:")
        # loop body: generic full steps (store addresses from a running pointer)
        for kk in (k, k + 1):
            nm = g.pmap(kk + 1)
            def hook(i, nm=nm):
                if i == g.loadat:
                    E(*loads(("full", 0), nm))
            g.step(E, kk, hook)
            m = g.pmap(kk)
            E(f"vse32.v v{m['v0']}, (a6)", "add a6, a6, t1", f"vse32.v v{m['v16']}, (a6)", "add a6, a6, t1")
        E("addi a7, a7, -1", "bnez a7, .Lgl")
        k += 2 * n
        continue
    ahead = STEPS[min(k + 1 + A.margin, NS - 1)]
    if k + 1 < NS and not done(need_st(ahead)) and q.ready():
        q.flush(E, REGS)
        q.batched(E, until=lambda: done(need_st(ahead)), sets=((12, 28), (8, 24)))
    if k + 1 < NS and not done(need_st(STEPS[k + 1])):
        raise RuntimeError(f"step {k + 1}: rows not produced")
    emit_step(k)
    k += 1
if not q.empty():
    raise RuntimeError("OPE work left after the GELU")
E(*fg.epilogue("s2"))
NAME = "p3_fused" if P3 else "p2_fused"
pathlib.Path(A.kernel).write_text(f"// GENERATED by script/tf/gemm_gelu.py --mode {A.mode}\n" +
                                  fg.wrap(NAME, f"void {NAME}(const uint32_t *a, const uint32_t *xpk, float *z)", L))
if P3:
    import subprocess
    here = pathlib.Path(__file__).parent
    subprocess.run([sys.executable, str(here / "gen_ln.py"), "--C", str(C), "--halfmajor", "1", "--kpstride", str(KP),
                    "--name", "p3_ln", "--out", str(pathlib.Path(A.kernel).parent / "p3_ln.c")], check=True,
                   stdout=subprocess.DEVNULL)
print(f"p2 fused: {len(L)} instructions, WIN {sorted(WIN)} FLUSH {FLUSH} XWIN {sorted(XWIN)} loadat {g.loadat} t3 {g.t3_first + 1}")
