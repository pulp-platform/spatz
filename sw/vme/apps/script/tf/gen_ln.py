"""Emit a LayerNorm-statistics + FP16 pack kernel for in[C][64] -> dstw[C/2][64] (Spatz VFU, e32 m4, vl = 64).

Same arithmetic as baseline tf16_layernorm_pack (opope_tf16.h): mean = sum_c x / C, var = sum_c (x - mean)^2 / C
+ 1e-5, r = TF_RSQRT(var) (magic constant + 3 Newton steps), y = (x - mean) * r narrowed to FP16 and packed by
channel pairs with two strided 16-bit stores (row 2p -> low half, row 2p+1 -> high half: O-POPE order).
Only the schedule differs: loads run ahead of their use, two accumulators (even/odd channels; the sums are
therefore added in a different order), channel pairs interleaved so dependent operations are never adjacent.
"""
import argparse
import pathlib
import struct

ap = argparse.ArgumentParser()
ap.add_argument("--C", type=int, default=64)
ap.add_argument("--name", default="vme_ln_pack")
ap.add_argument("--out", required=True)
ap.add_argument("--kpstride", type=int, default=0, help="K-pair rows per token half in the halfmajor layout (0: C/2)")
ap.add_argument("--halfmajor", type=int, default=0, help="1: output [2][C/2][32] (token-half-major) instead of [C/2][64]")
A = ap.parse_args()
C = A.C
assert C % 12 == 0 or C % 4 == 0

GPR = {"t0": 5, "t1": 6, "t2": 7, "a0": 10, "a1": 11, "a2": 12, "a3": 13}


def rr(vd, rs1, rs2):
    w = (0b110000 << 26) | (1 << 25) | (GPR[rs2] << 20) | (GPR[rs1] << 15) | (0b110 << 12) | (vd << 7) | 0x7B
    return f".word 0x{w:08x} /* p.vle32.v.rrpost v{vd}, ({rs1}), {rs2} */"


L = []


def e(*x):
    L.extend(x)


def fconst(reg, v):
    e(f"li t3, 0x{struct.unpack('<I', struct.pack('<f', v))[0]:08x}", f"fmv.w.x {reg}, t3")


VM4 = "vsetvli zero, t0, e32, m4, ta, ma"
e("li t0, 64", "li t2, 256", VM4)
fconst("ft0", 1.0 / C); fconst("ft1", 1e-5); fconst("ft2", 0.5); fconst("ft3", 1.5)

# ---- pass 1: mean. acc v0 / v4, ring of 6 buffers, loads 4 rows ahead ----
BUF = [8, 12, 16, 20, 24, 28]
AH = 4
e("mv a2, a1", "vmv.v.i v0, 0", "vmv.v.i v4, 0")
for r in range(AH):
    e(rr(BUF[r], "a2", "t2"))
for r in range(C):
    e(f"vfadd.vv v{4 * (r % 2)}, v{4 * (r % 2)}, v{BUF[r % 6]}")
    if r + AH < C:
        e(rr(BUF[(r + AH) % 6], "a2", "t2"))
e("vfadd.vv v0, v0, v4", "vfmul.vf v0, v0, ft0")              # M = v0

# ---- pass 2: variance. acc v4 / v8, channel pairs (v12, v16) / (v20, v24), next pair loaded early ----
P2 = [(12, 16), (20, 24)]
e("mv a2, a1", "vmv.v.i v4, 0", "vmv.v.i v8, 0", rr(12, "a2", "t2"), rr(16, "a2", "t2"))
for p in range(C // 2):
    xa, xb = P2[p % 2]
    e(f"vfsub.vv v{xa}, v{xa}, v0", f"vfsub.vv v{xb}, v{xb}, v0")
    if p + 1 < C // 2:
        na, nb = P2[(p + 1) % 2]
        e(rr(na, "a2", "t2"), rr(nb, "a2", "t2"))
    e(f"vfmul.vv v{xa}, v{xa}, v{xa}", f"vfmul.vv v{xb}, v{xb}, v{xb}",
      f"vfadd.vv v4, v4, v{xa}", f"vfadd.vv v8, v8, v{xb}")
e("vfadd.vv v4, v4, v8", "vfmul.vf v4, v4, ft0", "vfadd.vf v4, v4, ft1")
# TF_RSQRT(x = v4, t0 = v8, t1 = v12, t2 = v16) -> R = v8
e("vsrl.vi v8, v4, 1", "li t3, 0x5F3759DF", "vrsub.vx v8, v8, t3", "vfmul.vf v16, v4, ft2")
for _ in range(3):
    e("vfmul.vv v12, v8, v8", "vfmul.vv v12, v12, v16", "vfrsub.vf v12, v12, ft3", "vfmul.vv v8, v8, v12")
e("vmv.v.v v4, v8")                                           # R = v4

# ---- pass 3: y = (x - M) * R, narrow, pack. pairs (v8, v12) / (v16, v20), narrow temps v24 / v26 ----
P3 = [(8, 12), (16, 20)]
e("mv a2, a1", "mv a3, a0", "li t1, 4", *(["li t4, 32", f"li t5, {(A.kpstride or C // 2) * 128}"] if A.halfmajor else []),
  rr(8, "a2", "t2"), rr(12, "a2", "t2"))
for p in range(C // 2):
    xa, xb = P3[p % 2]
    e(f"vfsub.vv v{xa}, v{xa}, v0", f"vfsub.vv v{xb}, v{xb}, v0")
    if p + 1 < C // 2:
        na, nb = P3[(p + 1) % 2]
        e(rr(na, "a2", "t2"), rr(nb, "a2", "t2"))
    if A.halfmajor:
        # token half 0 -> a3, half 1 -> a3 + C/2 * 128 (t5); 16-bit strided stores at vl = 32 (t4 = 32)
        e(f"vfmul.vv v{xa}, v{xa}, v4", f"vfmul.vv v{xb}, v{xb}, v4",
          "vsetvli zero, t0, e16, m2, ta, ma",
          f"vfncvt.f.f.w v24, v{xa}", f"vfncvt.f.f.w v26, v{xb}", "vsetvli zero, t4, e16, m1, ta, ma",
          "vsse16.v v24, (a3), t1", "addi t3, a3, 2", "vsse16.v v26, (t3), t1", "add t3, a3, t5",
          "vsse16.v v25, (t3), t1", "addi t3, t3, 2", "vsse16.v v27, (t3), t1", "addi a3, a3, 128", VM4)
    else:
        e(f"vfmul.vv v{xa}, v{xa}, v4", f"vfmul.vv v{xb}, v{xb}, v4",
          "vsetvli zero, t0, e16, m2, ta, ma",
          f"vfncvt.f.f.w v24, v{xa}", f"vfncvt.f.f.w v26, v{xb}",
          "vsse16.v v24, (a3), t1", "addi t3, a3, 2", "vsse16.v v26, (t3), t1", "add a3, a3, t2",
          VM4)
e("fence rw, rw", "lw t3, -4(a3)", "ret")

N = A.name
body = "\n".join(f'    "{x}\\n"' for x in L)
src = (f"// GENERATED by script/gen_ln.py -- LayerNorm statistics + FP16 pack, same math as tf16_layernorm_pack\n"
       f"#include <stdint.h>\nvoid {N}(uint32_t *dstw, const float *in);\n"
       f'__asm__(\n    ".text\\n"\n    ".balign 64\\n"\n    ".globl {N}\\n"\n    ".type {N}, @function\\n"\n'
       f'    "{N}:\\n"\n{body}\n    ".size {N}, .-{N}\\n");\n')
pathlib.Path(A.out).write_text(src)
print(f"wrote {A.out} ({sum(1 for x in L if not x.endswith(':'))} instructions)")
