"""Data for the fused VME GeMM->ReLU (O-POPE P5 shape: C=128, T=64, COUT=192).

Inputs are drawn exactly as baseline_spatz/sw/opopeBenchmarks/common/tf16_data.py::p_lin(mode="p5")
(numpy default_rng(21): w = wgt(C, COUT) -> FP16, bias = 0.1*rnd(COUT), x = rnd(C, T) -> FP16), so the
values are identical to the O-POPE benchmark; only the memory layout differs:
  * VME packed pair word: {K even (hi half), K odd (lo half)} (OPE lane 0 = high half).
  * A operand (W^T, tile rows = output channels): stream [COUT/32][C/8][2][4][16] words: for every 32-channel
    block and every group of 4 K-pairs, the 4 K-pairs of the upper 16-channel tile (64 words) followed by those
    of the lower tile, so the whole A stream of one block is contiguous and one e32,m4 vle32 loads 4 operands.
  * B operand (X, tile columns = tokens):         [T/16][C/2][16] words.
  * Output Z^T[COUT][T] FP32 row-major, as O-POPE.
--bias 0 : golden = relu(W^T X)          (matmul-relu)
--bias 1 : golden = relu(W^T X + bias)   (gemm-relu, same as O-POPE P5)
"""
import argparse
import pathlib

import numpy as np

F32 = np.float32


def rnd(rng, shape, scale=1.0):
    return (rng.standard_normal(shape) * scale).astype(F32)


def wgt(rng, cin, cout):
    return (rng.standard_normal((cin, cout)) / np.sqrt(cin)).astype(F32)


def bits16(a):
    return np.asarray(a, np.float16).view(np.uint16).astype(np.uint32)


def vme_pack(m):
    """[R][C] FP16 -> [R/2][C] words {m[2p] hi, m[2p+1] lo}"""
    b = bits16(m)
    return (b[0::2] << 16) | b[1::2]


def opope_pack(m):
    """O-POPE layout {m[2p] lo, m[2p+1] hi} (only used for the equivalence check)"""
    b = bits16(m)
    return b[0::2] | (b[1::2] << 16)


def panels(packed, edge=16):
    """[P][N] words -> [N/edge][P][edge]"""
    p, n = packed.shape
    return packed.reshape(p, n // edge, edge).transpose(1, 0, 2).copy()


def carr(name, ctype, vals, fmt):
    body = ",\n".join(", ".join(fmt(v) for v in vals[i:i + 8]) for i in range(0, len(vals), 8))
    return (f"static {ctype} {name}[{len(vals)}] "
            f"__attribute__((section(\".data\"), aligned(64))) = {{\n{body}\n}};\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", required=True, type=pathlib.Path)
    ap.add_argument("--C", type=int, default=128)
    ap.add_argument("--T", type=int, default=64)
    ap.add_argument("--COUT", type=int, default=192)
    ap.add_argument("--bias", type=int, default=0)
    ap.add_argument("--kernel", default="p5", help="p5 (GeMM->ReLU), p6 (GeMM->softmax), p7 (p6 + cross entropy)")
    ap.add_argument("--dump-opope", type=pathlib.Path, default=None,
                    help="also dump the O-POPE-layout xpk/w/zinit as .npy for the equivalence check")
    a = ap.parse_args()
    C, T, O = a.C, a.T, a.COUT

    extra = {}
    if a.kernel == "p5":
        rng = np.random.default_rng(21)          # same draw order as tf16_data.p_lin
        w = wgt(rng, C, O).astype(np.float16)
        bias = 0.1 * rnd(rng, O)
        x16 = rnd(rng, (C, T)).astype(np.float16)
        z = w.astype(np.float64).T @ x16.astype(np.float64)
        if a.bias:
            z = z + bias.astype(np.float64)[:, None]
        golden = np.maximum(z, 0).astype(F32)
    else:                                        # same draw order as tf16_data.p_softmax (O = V)
        rng = np.random.default_rng(23)
        x16 = rnd(rng, (C, T)).astype(np.float16)
        w = (wgt(rng, C, O) * 2).astype(np.float16)
        bias = 0.1 * rnd(rng, O)
        z = w.astype(np.float64).T @ x16.astype(np.float64) + bias.astype(np.float64)[:, None]
        ez = np.exp(z - z.max(axis=0, keepdims=True))
        probs = ez / ez.sum(axis=0, keepdims=True)
        golden = probs.astype(F32)
        a.bias = 1
        if a.kernel == "p7":
            tok = rng.integers(0, O, T).astype(np.uint32)
            extra["d_tok"] = tok
            extra["d_loss"] = (-np.log(probs[tok, np.arange(T)])).astype(F32).view(np.uint32)
    zinit = np.repeat(bias.astype(F32)[:, None], T, axis=1) if a.bias else np.zeros((O, T), F32)

    if a.dump_opope and a.kernel == "p5":
        np.savez(a.dump_opope, xpk=opope_pack(x16), w=opope_pack(w),
                 zinit=np.repeat(bias.astype(F32)[:, None], T, axis=1))

    apan = panels(vme_pack(w))       # [O/16][C/2][16]
    apan = apan.reshape(O // 32, 2, C // 8, 4, 16).transpose(0, 2, 1, 3, 4).copy()  # [O/32][C/8][2][4][16]
    bpan = panels(vme_pack(x16))     # [T/16][C/2][16]
    hexw = lambda v: f"0x{int(v):08x}"
    out = ["// Generated by gen_data.py -- do not edit", "#pragma once", "#include <stdint.h>",
           f"#define C_SIZE {C}", f"#define T_SIZE {T}", f"#define COUT_SIZE {O}",
           f"#define HAS_BIAS {a.bias}", ""]
    out.append(carr("d_apan", "uint32_t", apan.ravel(), hexw))
    out.append(carr("d_bpan", "uint32_t", bpan.ravel(), hexw))
    out.append(carr("d_zinit", "uint32_t", zinit.view(np.uint32).ravel(), hexw))
    out.append(carr("d_golden", "uint32_t", golden.view(np.uint32).ravel(), hexw))
    # bias as one extra GeMM K-pair per 32-channel block: word = {hi (high half), lo (low half)},
    # hi = fp16(b), lo = fp16(b - hi) (|b - hi - lo| < 3e-8), multiplied by a {1.0, 1.0} operand.
    # Layout per cout-block (64 words, one e32,m4 load): [upper tile 16][lower tile 16][{1,1} x 16][0 x 16]
    hi = bias.astype(np.float16)
    lo = (bias.astype(np.float64) - hi.astype(np.float64)).astype(np.float16)
    bp = ((bits16(hi) << 16) | bits16(lo)).reshape(O // 32, 32)
    bvec = np.concatenate([bp, np.full((O // 32, 16), 0x3c003c00, np.uint32),
                           np.zeros((O // 32, 16), np.uint32)], axis=1)
    out.append(carr("d_bpair", "uint32_t", bvec.ravel(), hexw))
    for k, v in extra.items():
        out.append(carr(k, "uint32_t", np.asarray(v).ravel(), hexw))
    out.append(f"#define KERNEL_{a.kernel.upper()} 1")
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_text("\n".join(out))


if __name__ == "__main__":
    main()
