"""Emit a GELU + FP16 pack kernel: src[R][64] (FP32) -> dstw[R/2][64] (rows 2p -> low half, 2p+1 -> high half).

The arithmetic is taken verbatim from baseline TF16_GELU2 (opope_tf16_pairs.h, parsed from the header: tanh form,
TF_EXP degree-5 Taylor + six squarings, TF16_RECIP2), two rows per step as in tf16_gelu_pack. Only the schedule
differs: physical registers are renamed every row pair so that the next pair is loaded into registers that died
before the end of the current pair (its load latency is hidden), and the narrowing uses registers freed earlier.
"""
import argparse
import pathlib
import re
import struct

ap = argparse.ArgumentParser()
ap.add_argument("--rows", type=int, default=144)
ap.add_argument("--header", required=True, help="path to opope_tf16_pairs.h")
ap.add_argument("--name", default="vme_gelu_pack")
ap.add_argument("--loadat", type=int, default=62, help="issue the next pair's loads after this GELU2 op")
ap.add_argument("--out", required=True)
A = ap.parse_args()
R = A.rows
assert R % 4 == 0

# ---- parse TF16_GELU2 ----
txt = pathlib.Path(A.header).read_text()
body = txt[txt.index("#define TF16_GELU2()"):]
body = body[:body.index("while (0)")]
OPS = []                                    # (mnemonic, [operands], const kind, const value)
for m in re.finditer(r'asm volatile\("([^"]*)"\s*(?:::\s*"([fr])"\(([^)]*)\))?\)', body):
    ins, kind, val = m.group(1), m.group(2), m.group(3)
    mn, ops = ins.split(None, 1)
    ops = [o.strip() for o in ops.split(",")]
    OPS.append((mn, ops, kind, val))
assert len(OPS) == 68, len(OPS)

GPR = {"t0": 5, "t1": 6, "t2": 7, "a0": 10, "a1": 11, "a2": 12, "a3": 13}


def rr(vd, rs1, rs2):
    w = (0b110000 << 26) | (1 << 25) | (GPR[rs2] << 20) | (GPR[rs1] << 15) | (0b110 << 12) | (vd << 7) | 0x7B
    return f".word 0x{w:08x} /* p.vle32.v.rrpost v{vd}, ({rs1}), {rs2} */"


L = []


def e(*x):
    L.extend(x)


# constants -> FP / integer registers
fconsts, iconsts = {}, {}
for mn, ops, kind, val in OPS:
    if kind == "f":
        v = float(val.rstrip("f"))
        if v not in fconsts:
            fconsts[v] = f"ft{len(fconsts)}"
    elif kind == "r":
        v = int(val.rstrip("uU"), 0)
        iconsts.setdefault(v, ["t3", "t4"][len(iconsts)])
VM4 = "vsetvli zero, t0, e32, m4, ta, ma"
e("li t0, 64", "li t2, 256", "li t1, 4", VM4)
for v, r in fconsts.items():
    e(f"li t5, 0x{struct.unpack('<I', struct.pack('<f', v))[0]:08x}", f"fmv.w.x {r}, t5")
for v, r in iconsts.items():
    e(f"li {r}, 0x{v:08x}")

# logical -> physical. O-POPE roles: row a: v0 (x) v4 v8 v12, row b: v16 (x) v20 v24 v28.
# Next pair's x is loaded into the old v4 / v20 (last read by op 62), so roles x <-> v4 swap every pair.
def phys_map(p):
    if p % 2 == 0:
        return {"v0": 0, "v4": 4, "v8": 8, "v12": 12, "v16": 16, "v20": 20, "v24": 24, "v28": 28}
    return {"v0": 4, "v4": 0, "v8": 8, "v12": 12, "v16": 20, "v20": 16, "v24": 24, "v28": 28}


def emit_op(op, pm):
    mn, ops, kind, val = op
    o = [f"v{pm[x]}" if x in pm else x for x in ops]
    o = [(fconsts[float(val.rstrip('f'))] if kind == "f" else iconsts[int(val.rstrip('uU'), 0)]) if x == "%0" else x
         for x in o]
    e(f"{mn} {', '.join(o)}")


NP = R // 2
e("mv a2, a1", "mv a3, a0", rr(0, "a2", "t2"), rr(16, "a2", "t2"))       # pair 0 into v0 / v16
for p in range(NP):
    pm = phys_map(p)
    nm = phys_map(p + 1)
    for i, op in enumerate(OPS):
        emit_op(op, pm)
        if i + 1 == A.loadat and p + 1 < NP:
            e(rr(nm["v0"], "a2", "t2"), rr(nm["v16"], "a2", "t2"))
    xa, xb = pm["v0"], pm["v16"]
    # narrow + pack (O-POPE TF_NARROW_STORE2 order) into v8 / v24, free since op 63 / 64 of this pair
    e("vsetvli zero, t0, e16, m2, ta, ma", f"vfncvt.f.f.w v8, v{xa}", f"vfncvt.f.f.w v24, v{xb}",
      "vsse16.v v8, (a3), t1", "addi t5, a3, 2", "vsse16.v v24, (t5), t1", "add a3, a3, t2", VM4)
e("fence rw, rw", "lw t5, -4(a3)", "ret")

N = A.name
b = "\n".join(f'    "{x}\\n"' for x in L)
src = (f"// GENERATED by script/gen_gelu.py -- GELU + FP16 pack, same math as tf16_gelu_pack (TF16_GELU2)\n"
       f"#include <stdint.h>\nvoid {N}(uint32_t *dstw, const float *src);\n"
       f'__asm__(\n    ".text\\n"\n    ".balign 64\\n"\n    ".globl {N}\\n"\n    ".type {N}, @function\\n"\n'
       f'    "{N}:\\n"\n{b}\n    ".size {N}, .-{N}\\n");\n')
pathlib.Path(A.out).write_text(src)
print(f"wrote {A.out} ({len(L)} instructions)")
