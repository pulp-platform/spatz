"""Generate D=8 residual-VQ B and a packed-A FP16-to-FP32 GEMM reference."""
import argparse
from pathlib import Path

import hjson
import numpy as np


def initializer(array, dtype):
    if dtype == "float":
        return "{" + ", ".join(repr(float(x)) + "f" for x in array.flat) + "}"
    return "{" + ", ".join(hex(int(x)) for x in array.flat) + "}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("-c", "--cfg", type=Path, required=True)
    args = parser.parse_args()
    cfg = hjson.loads(args.cfg.read_text())
    m, n, k = (int(cfg[x]) for x in ("M", "N", "K"))
    if (m, n) != (64, 64) or k not in (128, 256, 512):
        parser.error("expected M64 N64 and K128, K256, or K512")
    if (int(cfg["TM"]), int(cfg["TN"])) != (16, 16):
        parser.error("expected TE=16")

    rng = np.random.default_rng(int(cfg.get("seed", 42)))
    a = rng.normal(size=(m, k)).astype(np.float16)
    cb0 = rng.normal(scale=0.5, size=(256, 8)).astype(np.float16)
    cb1 = rng.normal(scale=0.25, size=(256, 8)).astype(np.float16)
    idx0 = rng.integers(0, 256, size=(k, n // 8), dtype=np.uint8)
    idx1 = rng.integers(0, 256, size=(k, n // 8), dtype=np.uint8)
    scales = rng.uniform(0.5, 1.5, size=k).astype(np.float16)
    # Match the separate FP16 RVV vfadd and vfmul rounding.
    summed = (cb0[idx0].astype(np.float32) + cb1[idx1].astype(np.float32)).astype(np.float16)
    b = (summed.astype(np.float32) * scales[:, None, None].astype(np.float32)).astype(np.float16).reshape(k, n)
    # Bias seeds the accumulator before the first dot product.
    bias = rng.normal(size=(m, n)).astype(np.float32)
    reference = bias.copy()
    for q in range(0, k, 2):
        pair = (a[:, q, None].astype(np.float64) * b[None, q, :].astype(np.float64)
                + a[:, q + 1, None].astype(np.float64) * b[None, q + 1, :].astype(np.float64))
        reference = (reference.astype(np.float64) + pair).astype(np.float32)
    abits = a.view(np.uint16).astype(np.uint32)
    awords = (abits[:, 0::2] << 16) | abits[:, 1::2]
    apack = awords.reshape(m // 16, 16, k // 2).transpose(0, 2, 1).copy()
    # Pre-expand the indexed-load byte offsets and replicated scales in the
    # exact e16,m4 lane order consumed by each eight-K kernel iteration.
    meta = np.empty((n // 16, k // 8, 3, 128), dtype=np.uint16)
    scale_bits = scales.view(np.uint16)
    for nt in range(n // 16):
        for kg in range(k // 8):
            off0, off1, scale = meta[nt, kg]
            for pair in range(4):
                even_k = kg * 8 + pair * 2
                odd_k = even_k + 1
                for col in range(16):
                    lane = col % 8
                    group = nt * 2 + col // 8
                    j = pair * 32 + 2 * col
                    off0[j] = 2 * (8 * int(idx0[odd_k, group]) + lane)
                    off1[j] = 2 * (8 * int(idx1[odd_k, group]) + lane)
                    scale[j] = scale_bits[odd_k]
                    off0[j + 1] = 2 * (8 * int(idx0[even_k, group]) + lane)
                    off1[j + 1] = 2 * (8 * int(idx1[even_k, group]) + lane)
                    scale[j + 1] = scale_bits[even_k]

    lines = ["// Generated by script/gen_data.py; do not edit.",
             '#include "layer.h"', '#include "gemm.h"',
             f"const gemm_layer gemm_l = {{.M={m}, .N={n}, .K={k}}};"]
    for name, values, dtype in (
        ("Atpack_dram", apack, "uint32_t"),
        ("CB0_dram", cb0.view(np.uint16), "uint16_t"),
        ("CB1_dram", cb1.view(np.uint16), "uint16_t"),
        ("Cref_dram", reference, "float"),
        ("Cbias_dram", bias, "float"),
    ):
        lines.append(f'static {dtype} {name}[{values.size}] '
                     '__attribute__((section(".data"), aligned(64))) = '
                     + initializer(values, dtype) + ";")
    records = []
    for group in meta.reshape(-1, 3, 128):
        records.append("    {" + ", ".join(initializer(x, "uint16_t")
                                             for x in group) + "}")
    lines.append(f'static vq_group Bmeta_dram[{len(records)}] '
                 '__attribute__((section(".data"), aligned(64))) = {\n'
                 + ",\n".join(records) + "\n};")
    output = Path(__file__).resolve().parent.parent / "data" / f"data_{m}_{n}_{k}.h"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n\n".join(lines) + "\n")
    print(f"Written: {output}")


if __name__ == "__main__":
    main()
