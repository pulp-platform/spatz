"""P1 (LayerNorm -> GeMM, QKV-like projection), O-POPE shape C=96, T=64, COUT=176: VME data + kernels.
Inputs drawn exactly as baseline tf16_data.p_lin(mode="p1") (default_rng(21)); only the layouts differ:
  x [C][T] FP32 (input), lnpk [2][C/2][32] (LN output, token-half-major, written in the kernel),
  A = W' stream for the 1x2c GeMM (16 rows x 32 tokens, 4 K-pairs per group), bias' as one extra K-pair.
LayerNorm: O-POPE arithmetic (gen_ln.py), software pipelined; GeMM: vmegen 1x2c ping-pong blocks.
"""
import argparse, pathlib, subprocess, sys
import numpy as np
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "script" / "tf"))
import vmegen as vg

F32 = np.float32
ap = argparse.ArgumentParser()
ap.add_argument("--data", required=True)
ap.add_argument("--kernel", required=True)
ap.add_argument("--loadpos", type=int, default=4)
ap.add_argument("--drain", default="both")
A = ap.parse_args()
C, T, O = 96, 64, 176

def rnd(rng, shape, scale=1.0): return (rng.standard_normal(shape) * scale).astype(F32)
def wgt(rng, cin, cout): return (rng.standard_normal((cin, cout)) / np.sqrt(cin)).astype(F32)
def h(x): return np.asarray(x).astype(np.float16).astype(np.float64)
def ln_na(x):
    x = x.astype(np.float64); m = x.mean(axis=0, keepdims=True); v = ((x - m) ** 2).mean(axis=0, keepdims=True)
    return (x - m) / np.sqrt(v + 1e-5)
def fold_ln(w, g, b, bias):
    w64 = w.astype(np.float64)
    return (w64 * g.astype(np.float64)[:, None]).astype(np.float16), (bias.astype(np.float64) + w64.T @ b.astype(np.float64)).astype(F32)
rng = np.random.default_rng(21)
w = wgt(rng, C, O).astype(np.float16)
bias = 0.1 * rnd(rng, O)
x = rnd(rng, (C, T)); g = 1 + 0.1 * rnd(rng, C); b = 0.1 * rnd(rng, C)
w, bias = fold_ln(w, g, b, bias)
z = w.astype(np.float64).T @ h(ln_na(x)) + bias.astype(np.float64)[:, None]
arrays = {"d_x": x.view(np.uint32), "d_w_a": vg.pack_a(w, "1x2h", swap=True), "d_bv": vg.bias_vectors(bias, "1x2h"),
          "d_golden": z.astype(F32).view(np.uint32)}
out = ["// GENERATED by gen_p1f.py", "#pragma once", "#include <stdint.h>", f"#define C_SIZE {C}", f"#define T_SIZE {T}",
       f"#define COUT_SIZE {O}"]
for k, v in arrays.items():
    v = np.asarray(v).ravel()
    out.append(f"static uint32_t {k}[{len(v)}] __attribute__((section(\".data\"), aligned(64))) = {{" +
               ",".join(f"0x{int(q):08x}" for q in v) + "};")
pathlib.Path(A.data).write_text("\n".join(out) + "\n")

here = pathlib.Path(__file__).resolve().parents[3] / "script" / "tf"
ln = pathlib.Path(A.kernel).parent / "p1_ln.c"
subprocess.run([sys.executable, str(here / "gen_ln.py"), "--C", str(C), "--halfmajor", "1", "--name", "p1_ln",
                "--out", str(ln)], check=True, stdout=subprocess.DEVNULL)
gp = vg.Gemm(O, T, C // 2, shape="1x2c", bias=True, tag="p1", loadpos=A.loadpos, drain=A.drain)
src = ("// GENERATED by script/gen_ln_gemm.py\n#include <stdint.h>\n"
       "void p1_gemm(const uint32_t *a, const uint32_t *lnpk, float *z, const uint32_t *bv);\n" + gp.emit(name="p1_gemm"))
pathlib.Path(A.kernel).write_text(src)
print("p1: gemm", len(gp.L))
