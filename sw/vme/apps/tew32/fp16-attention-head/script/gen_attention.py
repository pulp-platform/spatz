"""P8 (attention head: S^T = K Q^T + mask -> causal softmax over keys, packed -> O^T = V^T P^T), O-POPE shape
D=64, T=96. Inputs drawn exactly as baseline tf16_data.p_attn (default_rng(24), 1/sqrt(d) folded into Q).
Score GeMM (2x1): A = K (W[D][T keys]) stream, B = Q^T panels, Z = Y = s (holds the causal mask, DMA'd outside
the measured region): blocks entirely above the diagonal are skipped (s keeps -1e30 there, never read as anything
else), blocks containing a diagonal tile are seeded with the mask, the others start from zero.
PV GeMM (1x2h): A = V (W[T keys][D]) in O-POPE half order, B = ppk [T/2][T] (packed by the softmax stage); the
reduction of column pair cb stops at key 32*cb+31 (later keys have probability 0 for these queries).
Causal softmax-pack: same op sequence as tf16_softmax_pack_causal (query chunks of 64 and 32, rows up to the
last query of the chunk), software pipelined (loads issued ahead, two max accumulators)."""
import argparse, pathlib, sys, struct
import numpy as np
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "script" / "tf"))
import vmegen as vg
F32 = np.float32
ap = argparse.ArgumentParser(); ap.add_argument("--data", required=True); ap.add_argument("--kernel", required=True)
A = ap.parse_args()
D, T = 64, 96
def rnd(rng, shape, scale=1.0): return (rng.standard_normal(shape) * scale).astype(F32)
def h(x): return np.asarray(x).astype(np.float16).astype(np.float64)
rng = np.random.default_rng(24)
q = rnd(rng, (D, T)).astype(np.float16); k = rnd(rng, (D, T)).astype(np.float16); v = rnd(rng, (T, D)).astype(np.float16)
qs = (q.astype(np.float64) * (1.0 / np.sqrt(D))).astype(np.float16)
s = np.asarray(h(k), np.float64).T @ np.asarray(h(qs), np.float64)
s = np.where(np.arange(T)[:, None] > np.arange(T)[None, :], -np.inf, s)
e_ = np.exp(s - s.max(axis=0, keepdims=True)); p16 = h(e_ / e_.sum(axis=0, keepdims=True))
out = np.asarray(h(v), np.float64).T @ p16
mask = np.where(np.arange(T)[:, None] > np.arange(T)[None, :], -1e30, 0.0).astype(F32)
arrays = {"d_k_a": vg.pack_a(k, "2x1"), "d_q_b": vg.pack_b_panels(qs), "d_mask": mask.view(np.uint32),
          "d_v_a": vg.pack_a(v, "1x2h", swap=True), "d_golden": out.astype(F32).view(np.uint32)}
o = ["// GENERATED by gen_p8.py", "#pragma once", "#include <stdint.h>", f"#define D_SIZE {D}", f"#define T_SIZE {T}"]
for kk, vv in arrays.items():
    vv = np.asarray(vv).ravel()
    o.append(f"static uint32_t {kk}[{len(vv)}] __attribute__((section(\".data\"), aligned(64))) = {{" +
             ",".join(f"0x{int(x):08x}" for x in vv) + "};")
pathlib.Path(A.data).write_text("\n".join(o) + "\n")

# ---- GeMMs ----
blocks1, seed1 = [], set()
for rg in range(T // 32):
    for ct in range(T // 16):
        kx, ky = 2 * rg, 2 * rg + 1
        if kx > ct:
            continue                                  # both tiles fully masked: skipped
        blocks1.append((rg, ct))
        if ct in (kx, ky):
            seed1.add((rg, ct))                       # contains a diagonal tile: Y = mask
g1 = vg.Gemm(T, T, D // 2, shape="2x1", order=blocks1, seed=True, seed_blocks=seed1, tag="s1")
g2 = vg.Gemm(D, T, T // 2, shape="1x2h", kp_fn=lambda blk: 16 * (blk[1] + 1), tag="s2")

# ---- causal softmax-pack ----
GPR = {"t0": 5, "t1": 6, "t2": 7, "a0": 10, "a1": 11, "a2": 12, "a3": 13}
def rr(vd, rs1, rs2):
    w = (0b110000 << 26) | (1 << 25) | (GPR[rs2] << 20) | (GPR[rs1] << 15) | (0b110 << 12) | (vd << 7) | 0x7B
    return f".word 0x{w:08x}"
L = []
def e(*x): L.extend(x)
def fc(r, val): e(f"li t3, 0x{struct.unpack('<I', struct.pack('<f', val))[0]:08x}", f"fmv.w.x {r}, t3")
RS = T * 4
e(f"li t2, {RS}", "li t1, 4")
for r_, v_ in (("ft0", -16.0), ("ft1", 0.015625), ("ft2", 0.0083333333), ("ft3", 0.0416666667),
               ("ft4", 0.1666666667), ("ft5", 0.5), ("ft6", 1.0), ("ft7", 2.0), ("ft8", -1e30)):
    fc(r_, v_)
# query chunks (q0, vl, rows): 0..31 with keys 0..31, then 32..95 with keys 0..95 (same elements as O-POPE's
# 0..63 / 64..95 split, but most of the work at vl = 64)
CHUNKS = [(0, 32, 32), (32, 64, 96)]
BUF = [8, 12, 16, 20, 24, 28]
for ci, (q0, vl, rmax) in enumerate(CHUNKS):
    VM = f"vsetvli zero, t0, e32, m4, ta, ma"
    e(f"li t0, {vl}", VM, f"addi a2, a1, {4 * q0}", "vfmv.v.f v0, ft8", "vfmv.v.f v4, ft8")
    for r in range(4):
        e(rr(BUF[r], "a2", "t2"))
    for r in range(rmax):
        e(f"vfmax.vv v{4 * (r % 2)}, v{4 * (r % 2)}, v{BUF[r % 6]}")
        if r + 4 < rmax:
            e(rr(BUF[(r + 4) % 6], "a2", "t2"))
    e("vfmax.vv v0, v0, v4", "vmv.v.i v4, 0", f"addi a2, a1, {4 * q0}", "mv a3, a2")
    P = [(16, 20), (24, 28)]
    e(rr(16, "a2", "t2"), rr(20, "a2", "t2"))
    for pq in range(rmax // 2):
        xa, xb = P[pq % 2]
        e(f"vfsub.vv v{xa}, v{xa}, v0", f"vfsub.vv v{xb}, v{xb}, v0")
        seq = [("vfmax.vf", "x", "ft0"), ("vfmul.vf", "x", "ft1"), ("vfmv.v.f", "t", "ft2")]
        for c in ("ft3", "ft4", "ft5", "ft6", "ft6"):
            seq += [("vfmul.vv", "t", None), ("vfadd.vf", "t", c)]
        seq += [("sq0", None, None)] + [("sq", None, None)] * 5
        for i, (op, d, c) in enumerate(seq):
            if i == 3 and pq + 1 < rmax // 2:
                na, nb = P[(pq + 1) % 2]
                e(rr(na, "a2", "t2"), rr(nb, "a2", "t2"))
            for x, t in ((xa, 8), (xb, 12)):
                if op == "vfmv.v.f": e(f"vfmv.v.f v{t}, {c}")
                elif op == "vfmul.vv": e(f"vfmul.vv v{t}, v{t}, v{x}")
                elif op == "vfadd.vf": e(f"vfadd.vf v{t}, v{t}, {c}")
                elif op in ("vfmax.vf", "vfmul.vf"): e(f"{op} v{x}, v{x}, {c}")
                elif op == "sq0": e(f"vfmul.vv v{x}, v{t}, v{t}")
                else: e(f"vfmul.vv v{x}, v{x}, v{x}")
        e(f"vse32.v v{xa}, (a3)", "add a3, a3, t2", f"vse32.v v{xb}, (a3)", "add a3, a3, t2",
          f"vfadd.vv v4, v4, v{xa}", f"vfadd.vv v4, v4, v{xb}")
    # TF_RECIP(v4 -> v8, temp v12)
    e("li t3, 0x7EF311C7", "vrsub.vx v8, v4, t3")
    for _ in range(3):
        e("vfmul.vv v12, v4, v8", "vfrsub.vf v12, v12, ft7", "vfmul.vv v8, v8, v12")
    # normalise + narrow + pack: pairs (v16, v20) / (v24, v28), narrow temps v12 / v14 (e16 m2 at vl <= 64)
    e(f"addi a2, a1, {4 * q0}", f"addi a3, a0, {4 * q0}", rr(16, "a2", "t2"), rr(20, "a2", "t2"))
    for pq in range(rmax // 2):
        xa, xb = P[pq % 2]
        if pq + 1 < rmax // 2:
            na, nb = P[(pq + 1) % 2]
            e(rr(na, "a2", "t2"), rr(nb, "a2", "t2"))
        e(f"vfmul.vv v{xa}, v{xa}, v8", f"vfmul.vv v{xb}, v{xb}, v8", "vsetvli zero, t0, e16, m2, ta, ma",
          f"vfncvt.f.f.w v0, v{xa}", f"vfncvt.f.f.w v2, v{xb}", "vsse16.v v0, (a3), t1", "addi t3, a3, 2",
          "vsse16.v v2, (t3), t1", "add a3, a3, t2", VM)
e("fence rw, rw", "lw t3, -4(a3)", "ret")
smb = "\n".join(f'    "{x}\\n"' for x in L)
sm = ('__asm__(\n    ".text\\n"\n    ".balign 64\\n"\n    ".globl p8_softmax_pack\\n"\n    ".type p8_softmax_pack, @function\\n"\n'
      f'    "p8_softmax_pack:\\n"\n{smb}\n    ".size p8_softmax_pack, .-p8_softmax_pack\\n");\n')
src = ("// GENERATED by script/gen_attention.py\n#include <stdint.h>\n"
       "void p8_gemm_s(const uint32_t *a, const uint32_t *b, float *s, const float *y);\n"
       "void p8_softmax_pack(uint32_t *ppk, float *s);\n"
       "void p8_gemm_o(const uint32_t *a, const uint32_t *ppk, float *o, const uint32_t *unused);\n" +
       g1.emit(name="p8_gemm_s") + sm + g2.emit(name="p8_gemm_o"))
pathlib.Path(A.kernel).write_text(src)
print("p8: blocks1", len(blocks1), "seeded", len(seed1), "| g1", len(g1.L), "sm", len(L), "g2", len(g2.L))
