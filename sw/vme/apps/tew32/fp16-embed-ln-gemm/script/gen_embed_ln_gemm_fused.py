"""P10 (embedding -> LayerNorm -> GeMM), O-POPE shape C=64, T=64, V=256, COUT=64: FUSED version (data + kernels).
Inputs drawn exactly as baseline tf16_data.p_embed (default_rng(26)); only the layouts differ.
  p10_emb_ln: embedding GeMM (2x1, A = wte stream, B = one-hot panels [T/16][V/2][16], Y = wpe^T seeded into the
    tiles, Z = emb [C][T]) whose one-hot panels are built inside it (token tile 0 between the seed rows of the
    first block, tiles 1..3 at the start of K-groups of the previous tile's blocks), followed in the same kernel by
    the LayerNorm (O-POPE arithmetic): the GeMM's last 32 tile rows are drained inside LN pass 1; pass 3 writes
    lnpk token-half-major [2][C/2][32].
  p10_prj_gemm: projection GeMM (1x2c: B = 4 contiguous K-pairs per load, no vl switch), bias' as one extra
    K-pair. Fusing the projection into LN pass 3 was measured slower: both are bound by scalar instruction issue.
"""
import argparse, pathlib, sys
import numpy as np
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "script" / "tf"))
import vmegen as vg

F32 = np.float32
ap = argparse.ArgumentParser()
ap.add_argument("--data", required=True)
ap.add_argument("--kernel", required=True)
ap.add_argument("--ohspread", type=int, default=4, help="K-groups between two injected one-hot tokens")
A = ap.parse_args()
C, T, V, O = 64, 64, 256, 64


def rnd(rng, shape, scale=1.0): return (rng.standard_normal(shape) * scale).astype(F32)
def wgt(rng, cin, cout): return (rng.standard_normal((cin, cout)) / np.sqrt(cin)).astype(F32)
def h(x): return np.asarray(x).astype(np.float16).astype(np.float64)
def ln_na(x):
    x = x.astype(np.float64); m = x.mean(axis=0, keepdims=True); v = ((x - m) ** 2).mean(axis=0, keepdims=True)
    return (x - m) / np.sqrt(v + 1e-5)
def fold_ln(w, g, b, bias):
    w64 = w.astype(np.float64)
    return (w64 * g.astype(np.float64)[:, None]).astype(np.float16), (bias.astype(np.float64) + w64.T @ b.astype(np.float64)).astype(F32)


rng = np.random.default_rng(26)
tok = rng.integers(0, V, T).astype(np.uint32)
wte = rnd(rng, (V, C)).astype(np.float16); wpe = 0.5 * rnd(rng, (T, C))
g = 1 + 0.1 * rnd(rng, C); b = 0.1 * rnd(rng, C)
w = wgt(rng, C, O).astype(np.float16); bias = 0.1 * rnd(rng, O)
w, bias = fold_ln(w, g, b, bias)
emb = (wte.astype(np.float32)[tok] + wpe).astype(np.float32).T
z = (w.astype(np.float64).T @ h(ln_na(emb)) + bias.astype(np.float64)[:, None]).astype(F32)

arrays = {"d_tok": tok, "d_wte_a": vg.pack_a(wte, "2x1"), "d_wpet": np.ascontiguousarray(wpe.T).view(np.uint32),
          "d_w_a": vg.pack_a(w, "1x2h", swap=True), "d_bv": vg.bias_vectors(bias, "1x2h"),
          "d_golden": z.view(np.uint32)}
out = ["// GENERATED by gen_embed_ln_gemm_fused.py", "#pragma once", "#include <stdint.h>",
       f"#define C_SIZE {C}", f"#define T_SIZE {T}", f"#define V_SIZE {V}", f"#define COUT_SIZE {O}"]
for k, v in arrays.items():
    v = np.asarray(v).ravel()
    out.append(f"static uint32_t {k}[{len(v)}] __attribute__((section(\".data\"), aligned(64))) = {{" +
               ",".join(f"0x{int(x):08x}" for x in v) + "};")
pathlib.Path(A.data).write_text("\n".join(out) + "\n")

# kernels: token-tile-major embedding GeMM (LayerNorm statistics need all channels of a token). The one-hot panels
# of token tiles 1..3 are built inside the GeMM (tile 0 between the seed rows of block 0): token t of tile tt+1 is written at the start of
# a K-group of the blocks of tile tt (scalar stores there do not wait for in-flight operand loads).
# s5 = tok pointer (tile tt+1), s7 = onehot panel base (tile tt+1) + 2, a7 = 0x3C00, temps t0 / t3.
order = [(rb, tt) for tt in range(T // 16) for rb in range(C // 32)]
KGE = V // 2 // 4
def onehot_tok(t, first):
    o = ["li a7, 0x3C00", "li t3, 8194", "add s7, s10, t3", "addi s5, s5, 64"] if first else []
    return o + [f"lw t0, {4 * (t % 16)}(s5)", "srli t3, t0, 1", "slli t3, t3, 6", "andi t0, t0, 1", "slli t0, t0, 1",
                "sub t3, t3, t0", "add t3, t3, s7", f"sh a7, {4 * (t % 16)}(t3)"]
plan = {}
for tt in range(T // 16 - 1):
    # groups of blocks (0, tt), (1, tt): j = 2 tt, 2 tt + 1; the last group of block 2tt+1 loads tile tt+1
    slots = [(2 * tt + jj, g) for jj in (0, 1) for g in range(KGE)][:-2]
    for k in range(16):
        jg = slots[min(k * A.ohspread, len(slots) - 1)]
        plan.setdefault(jg, []).extend(onehot_tok(16 * (tt + 1) + k, tt == 0 and k == 0))
        if k == 15 and tt + 1 < T // 16 - 1:
            plan[jg] += ["addi s5, s5, 64", "li t3, 8192", "add s7, s7, t3"]
def slot(j, g):
    return ((), (), plan.get((j, g), ()))


def seed_hook(i):
    """one-hot token i of tile 0, between the seed rows of block 0 (temps a0 / a1, a2 = 0x3C00, a3 = onehot + 2)"""
    o = ["li a2, 0x3C00", "addi a3, s10, 2"] if i == 0 else []
    return o + [f"lw a0, {4 * i}(s5)", "srli a1, a0, 1", "slli a1, a1, 6", "andi a0, a0, 1", "slli a0, a0, 1",
                "sub a1, a1, a0", "add a1, a1, a3", f"sh a2, {4 * i}(a1)"]


VM4 = "vsetvli zero, s0, e32, m4, ta, ma"
MM = ["msetmtype t4, t5", "msettn zero, t6"]
rr = vg.rr


def ln_tail(gm):
    """LayerNorm (same arithmetic as gen_ln.py / tf16_layernorm_pack) appended to the embedding GeMM: the last
    block's 32 tile rows (channels 32..63 of tokens 48..63, drain pointers a3/a5 and a4/a6) are drained inside
    pass 1, which reads them 12+ iterations later. The registers of the last K-group's operand set are written
    only after 14 VFU ops (pending vtfmm may still read them)."""
    e = gm.e
    last = vg.SETS2[(gm.gctr - 1) % 2]; other = vg.SETS2[gm.gctr % 2]
    O3, L3 = list(other), list(last)
    for reg, v in (("ft0", 1.0 / C), ("ft1", 1e-5), ("ft2", 0.5), ("ft3", 1.5)):
        import struct
        e(f"li t3, 0x{struct.unpack('<I', struct.pack('<f', v))[0]:08x}", f"fmv.w.x {reg}, t3")
    def buf(r):
        return O3[r % 3] if r < 16 else (L3 + O3)[(r - 16) % 6]
    e(VM4, "mv a2, s2", "vmv.v.i v12, 0", "vmv.v.i v28, 0")
    issued = 0
    def issue_upto(r, ah):
        nonlocal issued
        while issued < C and issued <= r + ah:
            q = issued
            if any(buf(x) == buf(q) for x in range(r + 1, q)):
                break
            e(rr(buf(q), "a2", "t2")); issued += 1
    issue_upto(-1, 2)
    drows = [("a5", "a3")] * 16 + [("a6", "a4")] * 16
    for r in range(C):
        acc = 12 if r % 2 == 0 else 28
        e(f"vfadd.vv v{acc}, v{acc}, v{buf(r)}")
        issue_upto(r, 2 if r < 14 else 4)
        if r % 2 == 0 and r < 32:
            ch = []
            for k in (r, r + 1):
                ts, ad = drows[k]
                ch += [f"vtse32 {ts}, ({ad})", f"addi {ts}, {ts}, 1", f"add {ad}, {ad}, s9"]
            e(*MM, *ch, VM4)
    e("vfadd.vv v0, v12, v28", "vfmul.vf v0, v0, ft0")                       # M = v0
    # pass 2: variance (gen_ln.py)
    P2 = [(12, 16), (20, 24)]
    e("mv a2, s2", "vmv.v.i v4, 0", "vmv.v.i v8, 0", rr(12, "a2", "t2"), rr(16, "a2", "t2"))
    for p in range(C // 2):
        xa, xb = P2[p % 2]
        e(f"vfsub.vv v{xa}, v{xa}, v0", f"vfsub.vv v{xb}, v{xb}, v0")
        if p + 1 < C // 2:
            na, nb = P2[(p + 1) % 2]
            e(rr(na, "a2", "t2"), rr(nb, "a2", "t2"))
        e(f"vfmul.vv v{xa}, v{xa}, v{xa}", f"vfmul.vv v{xb}, v{xb}, v{xb}", f"vfadd.vv v4, v4, v{xa}", f"vfadd.vv v8, v8, v{xb}")
    e("vfadd.vv v4, v4, v8", "vfmul.vf v4, v4, ft0", "vfadd.vf v4, v4, ft1")
    e("vsrl.vi v8, v4, 1", "li t3, 0x5F3759DF", "vrsub.vx v8, v8, t3", "vfmul.vf v16, v4, ft2")
    for _ in range(3):
        e("vfmul.vv v12, v8, v8", "vfmul.vv v12, v12, v16", "vfrsub.vf v12, v12, ft3", "vfmul.vv v8, v8, v12")
    e("vmv.v.v v4, v8")                                                       # R = v4
    # pass 3: y = (x - M) * R -> lnpk [2][C/2][32] (token-half-major)
    P3 = [(8, 12), (16, 20)]
    e("mv a2, s2", "lw a3, 48(sp)", "li t1, 4", "li t4, 32", f"li t5, {C // 2 * 128}", rr(8, "a2", "t2"), rr(12, "a2", "t2"))
    for p in range(C // 2):
        xa, xb = P3[p % 2]
        e(f"vfsub.vv v{xa}, v{xa}, v0", f"vfsub.vv v{xb}, v{xb}, v0")
        if p + 1 < C // 2:
            na, nb = P3[(p + 1) % 2]
            e(rr(na, "a2", "t2"), rr(nb, "a2", "t2"))
        e(f"vfmul.vv v{xa}, v{xa}, v4", f"vfmul.vv v{xb}, v{xb}, v4", "vsetvli zero, s0, e16, m2, ta, ma",
          f"vfncvt.f.f.w v24, v{xa}", f"vfncvt.f.f.w v26, v{xb}", "vsetvli zero, t4, e16, m1, ta, ma",
          "vsse16.v v24, (a3), t1", "addi t3, a3, 2", "vsse16.v v26, (t3), t1", "add t3, a3, t5",
          "vsse16.v v25, (t3), t1", "addi t3, t3, 2", "vsse16.v v27, (t3), t1", "addi a3, a3, 128", VM4)
    e("fence rw, rw", "lw t3, -4(a3)")


ge = vg.Gemm(C, T, V // 2, shape="2x1", order=order, seed=True, drain="alt", tag="emb")
gp = vg.Gemm(O, T, C // 2, shape="1x2c", bias=True, tag="prj")
src = ("// GENERATED by script/gen_embed_ln_gemm_fused.py\n#include <stdint.h>\n"
       "void p10_emb_ln(const uint32_t *a, const uint32_t *onehot, float *emb, const float *y, const uint32_t *tok,\n"
       "                uint32_t *lnpk);\n"
       "void p10_prj_gemm(const uint32_t *a, const uint32_t *lnpk, float *z, const uint32_t *bv);\n" +
       ge.emit(name="p10_emb_ln", slot=slot, pre_hook=lambda gm: gm.e("mv s5, a4", "sw a5, 48(sp)"),
               seed_hook=seed_hook, tail_hook=ln_tail) + gp.emit(name="p10_prj_gemm"))
pathlib.Path(A.kernel).write_text(src)
print("p10f: emb+ln", len(ge.L), "prj", len(gp.L))
