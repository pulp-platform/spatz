"""CNN layer (valid 3x3 conv + bias + ReLU, FP16 -> FP32), O-POPE shape Cin=32, H=W=16, Cout=64: VME data + kernel.

Inputs drawn exactly as baseline widening-hp-conv/script/gen_data.py (default_rng(1337)). Same formulation as
O-POPE (no im2col: one GeMM per filter tap on the input at a shifted address), Z[pos][cout] FP32 (pos = oy*W + ox,
row stride Cout). Only the output rows that are part of the result (oy < Ho, i.e. pos < Ho*W) are computed.
OPE: 2x1 blocks (32 positions x 16 outputs, two tiles) alternating the tile pairs, so a block is drained while the
next one accumulates. K-group = 2 K-pairs (input channel pairs) of one tap:
  A = input planes [Cin/2][H*W] words (O-POPE layout): two e32,vl=32 loads (planes c, c+1 at the tap shift, the
      pointer post-incremented by the plane stride),
  B = weights re-laid out [Cout/16][tap][Cin/2][16] (input placement): one e32,vl=32 load (2 K-pairs x 16 outputs).
Bias: one extra K-pair per block (A = constant {1,1} register, B = {bias hi, bias lo}). Two K-groups per vector /
matrix configuration switch, two register sets. ReLU (VFU, m8) over the result rows at the end, interleaved with
the drain of the last block.
"""
import argparse, pathlib, sys
import numpy as np
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "script" / "tf"))
import fusegen as fg

ap = argparse.ArgumentParser()
ap.add_argument("--data", required=True)
ap.add_argument("--kernel", required=True)
ap.add_argument("--batch", type=int, default=2)
ap.add_argument("--relu_in", type=int, default=0, help="1: ReLU of finished rows inside the OPE stream (vl = 32)")
A = ap.parse_args()
Cin, H, W, Cout, KH, KW = 32, 16, 16, 64, 3, 3
Ho, Wo = H - KH + 1, W - KW + 1
M = H * W
MV = Ho * W                         # result rows
KPC = Cin // 2
rng = np.random.default_rng(1337)
x = rng.uniform(-1, 1, (Cin, H, W)).astype(np.float16)
w = rng.uniform(-0.5, 0.5, (Cout, Cin, KH, KW)).astype(np.float16)
b = rng.uniform(-0.5, 0.5, Cout).astype(np.float32)
out = np.zeros((Ho, Wo, Cout), dtype=np.float64)
for ky in range(KH):
    for kx in range(KW):
        patch = x[:, ky:ky + Ho, kx:kx + Wo].astype(np.float64)
        out += np.einsum("chw,oc->hwo", patch, w[:, :, ky, kx].astype(np.float64))
out = np.maximum(out + b.astype(np.float64), 0).astype(np.float32).reshape(Ho * Wo, Cout)
PAD = 64
xb = x.view(np.uint16).reshape(Cin, H * W).astype(np.uint32)
xin = np.concatenate([(xb[0::2] | (xb[1::2] << 16)).ravel(), np.zeros(PAD, np.uint32)])
wb = w.view(np.uint16).astype(np.uint32)
wpair = wb[:, 0::2] | (wb[:, 1::2] << 16)                       # [Cout][Cin/2][KH][KW]
wr = wpair.reshape(Cout // 16, 16, KPC, KH * KW).transpose(0, 3, 2, 1)   # [ct][tap][kp][16]
hi = b.astype(np.float16); lo = (b.astype(np.float64) - hi.astype(np.float64)).astype(np.float16)
bw = (hi.view(np.uint16).astype(np.uint32)) | (lo.view(np.uint16).astype(np.uint32) << 16)   # {hi (lo half), lo}
arrays = {"cv_in": xin, "cv_w": wr.ravel(), "cv_bias": bw, "cv_golden": out.view(np.uint32).ravel()}
hdr = ["// GENERATED by gen_conv.py", "#pragma once", "#include <stdint.h>", f"#define CIN {Cin}", f"#define H_SIZE {H}",
       f"#define W_SIZE {W}", f"#define COUT {Cout}", f"#define KH_SIZE {KH}", f"#define KW_SIZE {KW}", f"#define HO_SIZE {Ho}",
       f"#define WO_SIZE {Wo}", f"#define M_SIZE {M}", f"#define K_SIZE {Cout}", f"#define IN_PAD {PAD}"]
for k, v in arrays.items():
    hdr.append(f"static uint32_t {k}[{len(v)}] __attribute__((section(\".data\"), aligned(64))) = {{" +
               ",".join(f"0x{int(q):08x}" for q in v) + "};")
pathlib.Path(A.data).write_text("\n".join(hdr) + "\n")

# ------------------------------------------------------------------ kernel ----------------------------------------
# s2 z, s3 in, s4 w (re-laid out), s5 bias; s1 = 32, s0 = 64; t1 = 1024 (plane stride), t2 = 128 (B group stride),
# s9 = 256 (z row stride); a0 A ptr, a1 B ptr; drains: a2/a3 (tile 0 addr / TSS), a4/a5 (tile 1).
L = []
def E(*x): L.extend(x)
V32 = "vsetvli zero, s1, e32, m2, ta, ma"
SETS = [[(0, 4), (8, 12)], [(16, 20), (24, 14)]]     # batch register sets: (A base 4 regs, B base 2 regs)
PAIRS = [("mt0", "mt4", fg.TS[0], fg.TS[1]), ("mt8", "mt12", fg.TS[2], fg.TS[3])]
NPB, NCT = MV // 32, Cout // 16
blocks = [(pb, ct) for pb in range(NPB) for ct in range(NCT)]
NG = KH * KW * KPC // 2                               # K-groups per block (72)

E(*fg.prologue(), "mv s2, a0", "mv s3, a1", "mv s4, a2", "mv s5, a3", "li s1, 32", "li s0, 64", "li t1, 1024",
  "li t2, 128", "li s9, 256", "li t4, 16450", "li t5, 0xC8", "li t6, 16",
  fg.VM64, "vle32.v v28, (s5)",                        # bias words of the 4 output tiles: v28..v31
  V32, "li t3, 0x3C003C00", "vmv.v.x v22, t3",          # {1, 1} (A of the bias K-pair)
  *fg.MM, "msettm zero, t6")


def tap_ptr(pb, tap):
    ky, kx = divmod(tap, KW)
    return (pb * 32 + ky * W + kx) * 4


def drain_rows(j):
    """32 rows of block j's tiles: (tile 0 row r, tile 1 row r) pairs, running pointers"""
    pb, ct = blocks[j]
    t0, t1, ts0, ts1 = PAIRS[j % 2]
    setup = [f"li a3, {ts0}", f"li a5, {ts1}", f"li t3, {(pb * 32) * 256 + ct * 64}", "add a2, s2, t3",
             f"li t3, {(pb * 32 + 16) * 256 + ct * 64}", "add a4, s2, t3"]
    rows = []
    for r in range(16):
        rows.append(["vtse32 a3, (a2)", "addi a3, a3, 1", "add a2, a2, s9"])
        rows.append(["vtse32 a5, (a4)", "addi a5, a5, 1", "add a4, a4, s9"])
    return setup, rows


def relu32(pb):
    """ReLU of the result rows of position block pb (image rows 2pb, 2pb+1; output columns ox < Wo only), vl = 32"""
    ops = []
    for oy in (2 * pb, 2 * pb + 1):
        for k in range(Wo * Cout // 32):
            o = [f"li t3, {oy * W * Cout * 4}", "add a6, s2, t3"] if k == 0 else []
            ops.append(o + ["vle32.v v6, (a6)", "vfmax.vf v6, v6, ft0", "vse32.v v6, (a6)", "addi a6, a6, 128"])
    return ops


E("fmv.w.x ft0, zero")
pending_dr = []
relu_q = []
bi = 0
for j, (pb, ct) in enumerate(blocks):
    t0, t1, _, _ = PAIRS[j % 2]
    # previous block's drain pointers, this block's operand pointers, zero + bias
    if j > 0:
        setup, pending_dr = drain_rows(j - 1)
        E(*setup)
    if A.relu_in and ct == 1 and pb >= 1:
        relu_q += relu32(pb - 1)                       # rows of pb-1: block (pb-1, 3) drained during (pb, 0)
    E(f"li t3, {tap_ptr(pb, 0)}", "add a0, s3, t3", f"li t3, {ct * KH * KW * KPC * 64}", "add a1, s4, t3",
      f"vtzero {t0}", f"vtzero {t1}", f"vtfmm.tvv {t0}, v22, v{28 + ct}", f"vtfmm.tvv {t1}, v22, v{28 + ct}")
    g = 0
    while g < NG:
        n = min(A.batch, NG - g)
        rs = SETS[bi % 2][:n] if n <= 2 else None
        bi += 1
        E(V32)
        if relu_q:
            E(*relu_q.pop(0))
        for k in range(n):
            gg = g + k
            if gg % (KPC // 2) == 0 and gg > 0:        # next tap: A pointer back to plane 0 at the new shift
                E(f"li t3, {tap_ptr(pb, gg // (KPC // 2))}", "add a0, s3, t3")
            a, bb = rs[k]
            E(fg.rr(a, "a0", "t1"), fg.rr(a + 2, "a0", "t1"), fg.rr(bb, "a1", "t2"))
        E(*fg.MM)
        for k in range(n):
            a, bb = rs[k]
            E(f"vtfmm.tvv {t0}, v{a}, v{bb}", f"vtfmm.tvv {t1}, v{a + 1}, v{bb}",
              f"vtfmm.tvv {t0}, v{a + 2}, v{bb + 1}", f"vtfmm.tvv {t1}, v{a + 3}, v{bb + 1}")
        # previous block's drain: one row per batch (32 rows over 36 batches)
        if pending_dr:
            E(*pending_dr.pop(0))
        g += n
    while pending_dr:
        E(*pending_dr.pop(0))
# last block: drain interleaved with the ReLU (m8, 128 words = 2 result rows per op, two ops per iteration)
setup, last_dr = drain_rows(len(blocks) - 1)
E(*setup)
# sync: the ReLU overwrites v0..v15, still operands of the last K-groups (no WAR protection for OPE reads):
# move a row of the last block's tile (waits for its last vtfmm) and read it from the scalar core
E(*fg.MM, f"li t3, {PAIRS[(len(blocks) - 1) % 2][2]}", "vtmv.v.t v6, t3", V32, "vmv.x.s t3, v6")
V8 = "vsetvli zero, t3, e32, m8, ta, ma"
E(V32)
for op in relu_q:                                      # leftovers of earlier position blocks (normally none)
    E(*op)
E("li t3, 128", V8)
first_pb = NPB - 1 if A.relu_in else 0
for oy in range(2 * first_pb, Ho):
    base = oy * W * Cout * 4
    nops = Wo * Cout // 128                             # 7 ops of 128 words (the 896 result words of an image row)
    E(f"li t3, {base}", "add a6, s2, t3", "li t3, 128")
    for k in range(0, nops, 2):
        two = k + 1 < nops
        E(f"vle32.v v0, (a6)", *([f"addi a7, a6, 512", "vle32.v v8, (a7)"] if two else []), "vfmax.vf v0, v0, ft0",
          *(["vfmax.vf v8, v8, ft0"] if two else []))
        if last_dr:
            E(*fg.MM, *[x for _ in range(4) if last_dr for x in last_dr.pop(0)], "li t3, 128", V8)
        E("vse32.v v0, (a6)", *(["vse32.v v8, (a7)"] if two else []), f"addi a6, a6, {1024 if two else 512}")
if last_dr:
    E(*fg.MM, *[x for r in last_dr for x in r])
    last_dr = []
E(*fg.epilogue("s2"))
pathlib.Path(A.kernel).write_text("// GENERATED by script/gen_conv.py\n" + fg.wrap(
    "conv_vme", "void conv_vme(float *z, const uint32_t *in, const uint32_t *w, const uint32_t *bias)", L))
print(f"conv: {len(L)} instructions, {len(blocks)} blocks x {NG} K-groups")
