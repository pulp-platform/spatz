# Required fields: TM, TN; optional fields: alpha (default 0.5), beta (default 0.25), seed (default 42).

import argparse
import pathlib

import hjson
import numpy as np
import torch

def array_to_cstr_f32(arr: np.ndarray) -> str:
    """Flat float32 array → C brace-initializer with 'f' suffix."""
    return "{" + ", ".join(repr(float(x)) + "f" for x in arr.flat) + "}"

def array_to_cstr_u32(arr: np.ndarray) -> str:
    return "{" + ", ".join(f"0x{int(x):08x}u" for x in arr.flat) + "}"

def pack_pairs(a, b, te):
    """Pack adjacent K positions into the two FP16 halves of one word."""
    m, k = a.shape
    n = b.shape[1]
    abits = a.view(np.uint16).astype(np.uint32)
    bbits = b.view(np.uint16).astype(np.uint32)
    aw = (abits[:, 0::2] << 16) | abits[:, 1::2]
    bw = (bbits[0::2, :] << 16) | bbits[1::2, :]
    return (aw.reshape(m // te, te, k // 2).transpose(0, 2, 1).copy(),
            bw.reshape(k // 2, n // te, te).transpose(1, 0, 2).copy())

def main():
    parser = argparse.ArgumentParser(
        description="Generate packed FP16-to-FP32 alpha-beta GEMM data"
    )
    parser.add_argument(
        "-c", "--cfg",
        type=pathlib.Path,
        required=True,
        help="JSON/HJSON config file (e.g. script/gemm_64_64_64.json)",
    )
    args = parser.parse_args()

    with args.cfg.open() as f:
        param = hjson.loads(f.read())

    M    = int(param["M"])
    N    = int(param["N"])
    K    = int(param["K"])
    TM   = int(param["TM"])
    TN   = int(param["TN"])
    alpha = np.float32(param.get("alpha", 0.5))
    beta  = np.float32(param.get("beta", 0.25))
    seed  = int(param.get("seed", 42))

    if M != 64 or N != 64 or K not in (128, 256, 512) or (TM, TN) != (16, 16):
        parser.error("this test targets M64_N64_K128, K256, or K512 with TE=16")

    torch.manual_seed(seed)

    A = torch.randn((M, K), dtype=torch.float32).to(torch.float16).numpy()
    B = torch.randn((K, N), dtype=torch.float32).to(torch.float16).numpy()
    bias = torch.randn((M, N), dtype=torch.float32).numpy()

    # Match SDOTP: each adjacent K pair is reduced and accumulated into FP32.
    product = np.zeros((M, N), dtype=np.float32)
    for k in range(0, K, 2):
        pair = (A[:, k, None].astype(np.float64) * B[None, k, :].astype(np.float64)
                + A[:, k + 1, None].astype(np.float64) * B[None, k + 1, :].astype(np.float64))
        product = (product.astype(np.float64) + pair).astype(np.float32)

    # Match the direct kernel: fma(alpha, product, round_fp32(beta * bias)).
    scaled_bias = (np.float64(beta) * bias.astype(np.float64)).astype(np.float32)
    C = (scaled_bias.astype(np.float64)
         + np.float64(alpha) * product.astype(np.float64)).astype(np.float32)
    A_pack, B_pack = pack_pairs(A, B, TM)

    lines = [
        "// Copyright 2026 ETH Zurich and University of Bologna.",
        "// Licensed under the Apache License, Version 2.0, see LICENSE for details.",
        "// SPDX-License-Identifier: Apache-2.0",
        "//",
        "// Author: Pei-Yu Lin, ETH Zürich",
        "//",
        "// Auto-generated by script/gen_data.py — do not edit by hand.",
        "",
        '#include "layer.h"',
        "",
        "const gemm_layer gemm_l = {",
        f"    .M  = {M},",
        f"    .N  = {N},",
        f"    .K  = {K},",
        "};",
        "",
        "// FP32 scalars in C = alpha * (A*B) + beta * bias.",
        "static float alpha_dram __attribute__((section(\".data\"), aligned(4))) =",
        f"    {repr(float(alpha))}f;",
        "static float beta_dram __attribute__((section(\".data\"), aligned(4))) =",
        f"    {repr(float(beta))}f;",
        "",
        "// FP32 golden reference: C = alpha * (A*B) + beta * bias.",
        f'static float Cref_dram[{M}*{N}] __attribute__((section(".data"))) =',
        array_to_cstr_f32(C) + ";",
        "",
        "",
        "// FP32 bias, with one independent value per output element.",
        f'static float Caddend_dram[{M}*{N}] __attribute__((section(".data"), aligned(64))) =',
        array_to_cstr_f32(bias) + ";",
        "",
        "// Atpack[m_tile][K/2][TE]: high half even K, low half odd K.",
        f'static uint32_t Atpack_dram[{K//2}*{M}] __attribute__((section(".data"), aligned(64))) =',
        array_to_cstr_u32(A_pack) + ";",
        "",
        "",
        "// Bpack[n_tile][K/2][TE], matching Atpack halfword order.",
        f'static uint32_t Bpack_dram[{K//2}*{N}] __attribute__((section(".data"), aligned(64))) =',
        array_to_cstr_u32(B_pack) + ";",
        "",
    ]

    out_dir = pathlib.Path(__file__).parent.parent / "data"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / f"data_{M}_{N}_{K}.h"

    with out_file.open("w") as f:
        f.write("\n".join(lines))

    print(f"Written: {out_file}")

if __name__ == "__main__":
    main()

