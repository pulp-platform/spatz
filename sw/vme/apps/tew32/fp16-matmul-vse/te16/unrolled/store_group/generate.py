#!/usr/bin/env python3
"""Expand the validated rolled store-group schedule into branch-free K kernels.

The emitted source retains the rolled kernel's instruction order. Only its
three fixed-trip-count C loops (M block, K group, store row) are expanded.
"""

from pathlib import Path


HERE = Path(__file__).resolve().parent
ROLLED = HERE.parents[1] / "rolled" / "store-group"


def expand_loop(source: str, marker: str, count: int) -> str:
    start = source.index(marker)
    brace = source.index("{", start)
    depth = 1
    end = brace + 1
    while depth:
        if source[end] == "{":
            depth += 1
        elif source[end] == "}":
            depth -= 1
        end += 1
    body = source[brace + 1 : end - 1]
    return source[:start] + "\n".join("{" + body + "}" for _ in range(count)) + source[end:]


def kernel_for(k: int) -> str:
    source = (ROLLED / "kernel" / "matmul.c").read_text()
    source = source.replace(
        "      const uintptr_t a_middle_end = a0p + (K_CHUNK / 8 - 1) * operand_group_bytes;\n",
        "",
    )
    source = expand_loop(source, "while (a0p != a_middle_end)", k // 8 - 1)
    source = source.replace(
        "      // Keep the pointer comparison; otherwise Clang adds a separate countdown.\n"
        '      asm volatile("" : "+r"(a0p));\n',
        "",
    )
    source = expand_loop(source, "for (uint32_t row = 4; row < TE; row += 4)", 3)
    source = expand_loop(source, "for (uint32_t nb = 0; nb < 4; nb += 1)", 4)
    source = source.replace("const uint32_t mb0 = nb * TE;", "const uint32_t mb0 = 0 * TE;", 1)
    for nb in range(1, 4):
        source = source.replace(
            "const uint32_t mb0 = nb * TE;", f"const uint32_t mb0 = {nb} * TE;", 1
        )
    source = source.replace(
        "// Process each 16-row output block independently; no state crosses blocks.",
        f"// K={k}: fixed M blocks, K groups, and store rows are fully expanded.\n"
        "  // Generated by unrolled/store_group/generate.py from rolled/store-group.",
    )
    assert "while (" not in source and "for (" not in source
    assert "nb * TE" not in source
    assert source.count("vtfmm.tvv") == 4 * (k // 8) * 16
    return source


for k in (128, 256, 512):
    target = HERE / f"K{k}"
    for name in ("main.c", "kernel/matmul.h", "data/layer.h", "script/gen_data.py"):
        dest = target / name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_bytes((ROLLED / name).read_bytes())
    kernel = target / "kernel/matmul.c"
    kernel.write_text(kernel_for(k))
    config = target / "script" / f"matmul_64_64_{k}.json"
    config.write_text(f"{{ M: 64, N: 64, K: {k}, TM: 16, TN: 16, seed: 42 }}\n")
