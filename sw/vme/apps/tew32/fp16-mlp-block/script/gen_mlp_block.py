"""P9 (MLP block: LN -> GeMM1 -> GELU -> GeMM2 + residual), O-POPE shape C=64, T=64, HID=144: data + GeMMs.
Inputs drawn exactly as baseline tf16_data.p_mlp (default_rng(25)). Layouts:
  GeMM1 (1x2h): A = w1' (W[C][HID]) in O-POPE half order (B = lnpk packed by the LayerNorm stage), bias1' as an
                extra K-pair, Z = h [HID][T].
  GeMM2 (1x2h): A = [w2; b2; 0] (W[HID+2][C], O-POPE half order: bias2 is one more reduction row, hpk row HID/2
                = {1.0, 0}), Y = residual x seeded into the tiles, Z = z [C][T] (in place over x)."""
import argparse, pathlib, sys
import numpy as np
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[3] / "script" / "tf"))
import vmegen as vg
F32 = np.float32
ap = argparse.ArgumentParser(); ap.add_argument("--data", required=True); ap.add_argument("--kernel", required=True)
A = ap.parse_args()
C, T, H = 64, 64, 144
def rnd(rng, shape, scale=1.0): return (rng.standard_normal(shape) * scale).astype(F32)
def wgt(rng, cin, cout): return (rng.standard_normal((cin, cout)) / np.sqrt(cin)).astype(F32)
def h(x): return np.asarray(x).astype(np.float16).astype(np.float64)
def ln_na(x):
    x = x.astype(np.float64); m = x.mean(axis=0, keepdims=True); v = ((x - m) ** 2).mean(axis=0, keepdims=True)
    return (x - m) / np.sqrt(v + 1e-5)
def fold_ln(w, g, b, bias):
    w64 = w.astype(np.float64)
    return (w64 * g.astype(np.float64)[:, None]).astype(np.float16), (bias.astype(np.float64) + w64.T @ b.astype(np.float64)).astype(F32)
def gelu(x): return 0.5 * x * (1.0 + np.tanh(np.sqrt(2.0 / np.pi) * (x + 0.044715 * x ** 3)))
def lin(w, a, b=None):
    z = w.astype(np.float64).T @ np.asarray(a, dtype=np.float64)
    return z if b is None else z + b.astype(np.float64)[:, None]

rng = np.random.default_rng(25)
x = rnd(rng, (C, T)); g = 1 + 0.1 * rnd(rng, C); b = 0.1 * rnd(rng, C)
w1 = wgt(rng, C, H).astype(np.float16); b1 = 0.1 * rnd(rng, H)
w2 = wgt(rng, H, C).astype(np.float16); b2 = 0.1 * rnd(rng, C)
w1, b1 = fold_ln(w1, g, b, b1)
b2 = b2.astype(np.float16).astype(np.float64)
z = x + lin(w2, h(gelu(lin(w1, h(ln_na(x)), b1))), b2)
w2full = np.zeros((H + 2, C), np.float16); w2full[:H] = w2; w2full[H] = b2.astype(np.float16)
arrays = {"d_x": x.view(np.uint32), "d_w1_a": vg.pack_a(w1, "1x2h", swap=True), "d_bv1": vg.bias_vectors(b1, "1x2h"),
          "d_w2_a": vg.pack_a(w2full, "1x2h", swap=True), "d_hone": np.full(T, 0x3C00, np.uint32),
          "d_golden": z.astype(F32).view(np.uint32)}
out = ["// GENERATED by gen_p9.py", "#pragma once", "#include <stdint.h>",
       f"#define C_SIZE {C}", f"#define T_SIZE {T}", f"#define HID_SIZE {H}"]
for k, v in arrays.items():
    v = np.asarray(v).ravel()
    out.append(f"static uint32_t {k}[{len(v)}] __attribute__((section(\".data\"), aligned(64))) = {{" +
               ",".join(f"0x{int(q):08x}" for q in v) + "};")
pathlib.Path(A.data).write_text("\n".join(out) + "\n")
g1 = vg.Gemm(H, T, C // 2, shape="1x2h", bias=True, tag="g1")
# GeMM2: Y = residual x seeded into the tiles (measured faster than staging W2^T h + b2 and adding x on the VFU)
g2 = vg.Gemm(C, T, (H + 2) // 2, shape="1x2h", seed=True, drain="alt", tag="g2")
src = ("// GENERATED by script/gen_mlp_block.py\n#include <stdint.h>\n"
       "void p9_gemm1(const uint32_t *a, const uint32_t *lnpk, float *h, const uint32_t *bv);\n"
       "void p9_gemm2(const uint32_t *a, const uint32_t *hpk, float *z, const float *y);\n" +
       g1.emit(name="p9_gemm1") + g2.emit(name="p9_gemm2"))
pathlib.Path(A.kernel).write_text(src)
print("p9: g1", len(g1.L), "g2", len(g2.L))
