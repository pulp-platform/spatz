import argparse
import json
import pathlib

import numpy as np


def c_array(name, values, ctype):
    flat = np.asarray(values).ravel()
    body = ", ".join(f"0x{int(value):08x}" for value in flat)
    return (f"static const {ctype} {name}[{flat.size}] "
            f"__attribute__((section(\".data\"))) = {{{body}}};\n\n")


def pack_reduction_pairs(matrix, reduction_axis):
    bits = np.ascontiguousarray(matrix, dtype=np.float16).view(np.uint16)
    if reduction_axis == 1:
        bits = bits.T
    if bits.shape[0] & 1:
        bits = np.concatenate((bits, np.zeros((1, bits.shape[1]), np.uint16)))
    return (bits[0::2].astype(np.uint32) |
            (bits[1::2].astype(np.uint32) << 16))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    config = json.loads(pathlib.Path(args.config).read_text())
    M, N, K = (int(config[key]) for key in ("M", "N", "K"))
    if min(M, N, K) < 1:
        raise ValueError("M, N, and K must be positive")

    rng = np.random.default_rng(int(config.get("seed", 42)))
    a = rng.uniform(-1.0, 1.0, (M, K)).astype(np.float16)
    b = rng.uniform(-1.0, 1.0, (K, N)).astype(np.float16)
    result = a.astype(np.float32) @ b.astype(np.float32)

    apack = pack_reduction_pairs(a, reduction_axis=1)
    bpack = pack_reduction_pairs(b, reduction_axis=0)

    output = pathlib.Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    text = (
        "// Generated by script/gen_data.py.\n"
        "// SPDX-License-Identifier: Apache-2.0\n\n"
        "#include <stdint.h>\n"
        "#include \"layer.h\"\n\n"
        f"static const gemm_layer gemm_l = {{{M}, {N}, {K}}};\n\n"
        + c_array("gemm_Apack_dram", apack, "uint32_t")
        + c_array("gemm_Bpack_dram", bpack, "uint32_t")
        + c_array("gemm_result_bits", result.view(np.uint32), "uint32_t")
    )
    output.write_text(text)


if __name__ == "__main__":
    main()
