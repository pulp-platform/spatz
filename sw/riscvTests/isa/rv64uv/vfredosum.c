static inline uint32_t get_vlenb_hw(void) {
  uint32_t vl;
  asm volatile("vsetvli %0, %1, e8, m1, ta, ma" : "=r"(vl) : "r"(1024));
  return vl;                       // 32 on smallvrf, 64 on standard
}

